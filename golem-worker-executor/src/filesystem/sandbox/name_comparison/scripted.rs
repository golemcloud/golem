pub(in crate::filesystem::sandbox) use super::insensitive_mode::NativeNameComparisonMode;
use std::ffi::OsStr;

pub(super) fn names_equal(left: &OsStr, right: &OsStr) -> bool {
    left.to_string_lossy()
        .eq_ignore_ascii_case(&right.to_string_lossy())
}
