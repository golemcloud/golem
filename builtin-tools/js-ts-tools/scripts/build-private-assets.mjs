import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');

function collect(directory, relative = '') {
  const files = [];
  for (const name of readdirSync(directory).sort()) {
    const source = path.join(directory, name);
    const child = relative ? `${relative}/${name}` : name;
    if (statSync(source).isDirectory()) files.push(...collect(source, child));
    else files.push([child, readFileSync(source, 'utf8')]);
  }
  return files;
}

const npmRoot = path.join(root, 'node_modules/npm');
const typescriptRoot = path.join(root, 'node_modules/typescript');

// Rollup contains npm's complete executable module graph. Only user-facing manual pages remain as
// data files; no npm dependency/package tree is carried into the tool component.
const npmFiles = collect(path.join(npmRoot, 'man')).map(([name, contents]) => [
  `man/${name}`,
  contents,
]);

// Rollup contains tsc's executable module graph. The compiler still reads its standard libraries
// and optional localized diagnostics as data, so keep just those non-executable assets.
const typescriptFiles = [
  ['package.json', readFileSync(path.join(typescriptRoot, 'package.json'), 'utf8')],
  ...collect(path.join(typescriptRoot, 'lib'))
    .filter(([name]) => name.endsWith('.d.ts') || name.endsWith('.json'))
    .map(([name, contents]) => [`lib/${name}`, contents]),
];

const renderFiles = (entries) => `Object.freeze(${JSON.stringify(Object.fromEntries(entries))})`;
const npmOutput = [
  '// Generated by scripts/build-private-assets.mjs. Do not edit.',
  `export const npmBundleSource = ${JSON.stringify(readFileSync(path.join(root, 'generated/npm-cli.cjs'), 'utf8'))};`,
  `export const npmPrivateFiles = ${renderFiles(npmFiles)};`,
  '',
].join('\n');
const typescriptOutput = [
  '// Generated by scripts/build-private-assets.mjs. Do not edit.',
  `export const tscBundleSource = ${JSON.stringify(readFileSync(path.join(root, 'generated/tsc.cjs'), 'utf8'))};`,
  `export const typescriptPrivateFiles = ${renderFiles(typescriptFiles)};`,
  '',
].join('\n');

writeFileSync(path.join(root, 'generated/npm-assets.ts'), npmOutput);
writeFileSync(path.join(root, 'generated/typescript-assets.ts'), typescriptOutput);
