import fc from "fast-check"
import { describe, expect, it } from "vitest"
import { SchemaBuilder, mergeGraphDefs } from "../src/internal/schema-model/builder.js"
import {
  canonicalSchemaBytesV1,
  schemaFingerprintV1,
} from "../src/internal/schema-model/fingerprint.js"
import {
  emptyMetadata,
  field,
  schemaType,
  t,
  type DiscriminatorRule,
  type SchemaGraph,
  type SchemaType,
} from "../src/internal/schema-model/model.js"
import { validateSchemaGraph } from "../src/internal/schema-model/validation.js"

const hex = (bytes: Uint8Array): string =>
  [...bytes].map((byte) => byte.toString(16).padStart(2, "0")).join("")
const graph = (root: SchemaType): SchemaGraph => ({ defs: new Map(), root })
const metadata = emptyMetadata()
const branch = (tag: string, body: SchemaType, discriminator: DiscriminatorRule) => ({
  tag,
  body,
  discriminator,
  metadata: emptyMetadata(),
})
const codes = (root: SchemaType): string[] =>
  validateSchemaGraph(graph(root)).map((error) => error.code)

// These vectors are copied from the platform-owned Rust golden corpus and are also exercised by
// the canonical TypeScript, Scala, Rust SDK re-export, and MoonBit suites. The bytes below are
// constants rather than output generated by another implementation in this test.
