#!/usr/bin/env python3
"""Generates sdk/src/wasmWasiMain/kotlin/cloud/golem/wasm/SchemaTags.kt from the WIT.

The canonical-ABI tag of a variant case is its position in the declaration, so inserting a case
mid-variant (as Golem 1.6.0 did with `uuid-type` / `uuid-value`) silently shifts every later tag.
Never hard-code these numbers: re-run this script after scripts/sync-wit.sh.

Usage: scripts/gen-schema-tags.py [--check]
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
WIT = HERE / "wit-native/deps/golem-core-v2/golem-core-v2.wit"
OUT = HERE / "sdk/src/wasmWasiMain/kotlin/cloud/golem/wasm/SchemaTags.kt"


def cases(src: str, variant: str):
    m = re.search(r"variant " + re.escape(variant) + r" \{(.*?)\n    \}", src, re.S)
    if not m:
        sys.exit(f"variant {variant} not found in {WIT}")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    names = []
    for line in body.split("\n"):
        line = line.strip().rstrip(",")
        if line:
            names.append(re.split(r"[(\s]", line)[0])
    return names


def const_name(case: str, suffixes) -> str:
    for suffix in suffixes:
        if case.endswith(suffix):
            case = case[: -len(suffix)]
            break
    return case.upper().replace("-", "_")


def render() -> str:
    src = WIT.read_text()
    types = cases(src, "schema-type-body")
    values = cases(src, "schema-value-node")
    lines = [
        "// GENERATED by sdks/kotlin/scripts/gen-schema-tags.py from wit-native/deps/golem-core-v2 -- do not edit.",
        "package cloud.golem.wasm",
        "",
        "/** Canonical-ABI variant tags of golem:core/types@2.0.0 `schema-type-body` and `schema-value-node`. */",
        "internal object SchemaTags {",
        f"    // schema-type-body: {len(types)} cases",
    ]
    for i, c in enumerate(types):
        lines.append(f"    const val TYPE_{const_name(c, ['-type'])} = {i}")
    lines.append("")
    lines.append(f"    // schema-value-node: {len(values)} cases")
    for i, c in enumerate(values):
        lines.append(f"    const val VALUE_{const_name(c, ['-value-node', '-value', '-handle'])} = {i}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("SchemaTags.kt is out of date: run sdks/kotlin/scripts/gen-schema-tags.py")
        print("SchemaTags.kt is up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


main()
