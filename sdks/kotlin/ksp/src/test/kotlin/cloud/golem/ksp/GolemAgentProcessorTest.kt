    @Test
    fun `registers top-level Tool functions from every tool export`() {
        val tools = SourceFile.kotlin(
            "Tools.kt",
            """
            package example

            import cloud.golem.annotations.Tool

            @Tool(name = "kt-echo", description = "Echoes its input")
            fun ktEcho(value: String): String = "kt:" + value

            @Tool(name = "kt-add")
            fun ktAdd(a: Int, b: Int): Int = a + b

            @Tool(name = "kt-ping")
            fun ktPing() {}

            @Tool(name = "kt-upper", stdin = true, stdout = true)
            fun ktUpper(prefix: String, io: cloud.golem.runtime.ToolStreams): Int = 0
            """.trimIndent(),
        )
        val compilation = runProcessor(tools)
        val entry = generated(compilation, "GolemGeneratedGuest.kt")
        assertContains(entry, "fun registerAllTools()")
        assertContains(entry, "cloud.golem.runtime.NativeToolDescriptor(\"kt-echo\", \"Echoes its input\", listOf(cloud.golem.runtime.NativeToolParamSchema(\"value\", \"string\")), \"string\", false, false, false, ")
        assertContains(entry, "SchemaValue.Str(example.ktEcho((input[0] as SchemaValue.Str).v))")
        assertContains(entry, "\"kt-add\"")
        assertContains(entry, "SchemaValue.S32(example.ktAdd((input[0] as SchemaValue.S32).v, (input[1] as SchemaValue.S32).v))")
        assertContains(entry, "{ _, _ -> example.ktPing(); SchemaValue.Unit_ }")
        // A ToolStreams parameter is not a positional; it receives the invocation's streams at its own position.
        assertContains(entry, "\"kt-upper\", \"\", listOf(cloud.golem.runtime.NativeToolParamSchema(\"prefix\", \"string\")), \"s32\", true, true, false, ")
        assertContains(entry, "example.ktUpper((input[0] as SchemaValue.Str).v, streams)")
        // The host may call discover-tools before anything else, so every tool export registers first.
        for (export in listOf("discover-tools", "get-tool", "invoke")) {
            val body = entry.substringAfter("@WasmExport(\"golem:tool/guest@0.1.0#$export\")").substringBefore("@WasmExport")
            assertContains(body, "registerAllTools()")
        }
    }

