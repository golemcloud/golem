    @Test
    fun `one interface can be the agent contract and the RPC client contract`() {
        val sources = SourceFile.kotlin(
            "SharedRpcContract.kt",
            """
            package shared

            import cloud.golem.annotations.Agent
            import cloud.golem.annotations.Endpoint
            import cloud.golem.annotations.RemoteAgent
            import cloud.golem.BaseAgent

            @RemoteAgent(typeName = "TallyAgent")
            interface TallyContract {
                @Endpoint(post = "/bump")
                fun bump(by: Int): Int
            }

            @Agent(typeName = "TallyAgent", mount = "/tallies/{name}")
            class TallyAgent(val name: String) : BaseAgent(), TallyContract {
                private var total = 0
                override fun bump(by: Int): Int { total += by; return total }
            }
            """.trimIndent(),
        )
        val compilation = runProcessor(sources)

        // The agent registers the contract's endpoint under the shared type name ...
        val reg = generated(compilation, "TallyAgentRegistration.kt")
        assertContains(reg, "\"TallyAgent\",")
        assertContains(reg, "NativeHttpEndpoint(\"POST\", \"/bump\"")
        // ... and the generated client implements the same interface, so the caller's surface and the
        // implementation are checked against one declaration rather than correlated by a string alone.
        val rpc = generated(compilation, "TallyContractRpc.kt")
        assertContains(rpc, "TallyContract")
        assertContains(rpc, "\"TallyAgent\"")
    }

