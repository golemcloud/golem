    @Test
    fun `an explicit @Agent typeName overrides the class name on the wire`() {
        val agent = SourceFile.kotlin(
            "CounterAgentImpl.kt",
            """
            package renamed

            import cloud.golem.annotations.Agent
            import cloud.golem.annotations.Endpoint
            import cloud.golem.BaseAgent

            @Agent(typeName = "Counter", mount = "/counters/{name}")
            class CounterAgentImpl(val name: String) : BaseAgent() {
                @Endpoint(get = "/value")
                fun value(): Int = 1
            }
            """.trimIndent(),
        )
        val reg = generated(runProcessor(agent), "CounterAgentImplRegistration.kt")

        // Assert the descriptor's first three fields together: type name, description, mount. An
        // unknown or shifted annotation argument moves a value between them and would pass a
        // single-field assertion -- KSP binds a named argument it does not know onto the first
        // declared parameter instead of rejecting it.
        assertContains(reg, "\"Counter\",\n            \"\",\n            \"/counters/{name}\",")
        assertContains(reg, "fun registerCounterAgentImpl()")
        assertContains(reg, "(instance as CounterAgentImpl).value()")
    }

