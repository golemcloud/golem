package cloud.golem.ksp

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies

private const val R = "cloud.golem.runtime"

/**
 * Generates the typed surface of a `@ToolDefinition` interface `X`, all public and in the interface's package so that a library can declare
 * the interface and another module can use it: `XDefinition` (the tool record and error codecs), `XClient` (typed calls through `ToolRpc`),
 * `XUnderlying` (the typed handle a middleware receives), `XMiddleware` (transparent base class) and `XAdapter<U>` (adapter base class).
 */
class ToolDefinitionEmitter(private val codeGenerator: CodeGenerator) {

    fun emit(model: ToolDefinitionModel) {
        val x = model.interfaceName
        val code = buildString {
            appendLine("// AUTO-GENERATED by golem-kotlin-ksp — do not edit")
            appendLine("package ${model.packageName}")
            appendLine()
            appendLine("import $R.SchemaValue")
            appendLine("import $R.callTyped")
            appendLine("import $R.callTypedWithOutputs")
            appendLine("import $R.noDeclaredErrorDecoder")
            appendLine()
            append(definitionObject(model))
            appendLine()
            append(client(model))
            appendLine()
            append(underlying(model))
            appendLine()
            append(middleware(model))
            appendLine()
            append(adapter(model))
        }
        codeGenerator.createNewFile(
            dependencies = Dependencies.ALL_FILES,
            packageName = model.packageName,
            fileName = "${x}Tool",
            extensionName = "kt",
        ).bufferedWriter().use { it.write(code) }
    }

    private fun definitionObject(m: ToolDefinitionModel): String = buildString {
        val flat = m.flatCommands()
        appendLine("/** The definition of the tool ${doc(m.name)}: its command tree for the host, and the codecs of its declared errors. */")
        appendLine("object ${m.interfaceName}Definition {")
        appendLine("    val tool = $R.NativeToolDefinition(")
        appendLine("        name = ${lit(m.name)}, version = ${lit(m.version)}, summary = ${lit(m.summary)}, requiresFilesystem = ${m.requiresFilesystem},")
        appendLine("        commands = listOf(")
        for (c in flat) appendLine("            ${nativeCommand(c)},")
        appendLine("        ),")
        val groups = allGroups(m, emptyList())
        if (groups.isNotEmpty()) {
            appendLine("        groups = listOf(")
            for ((path, g) in groups) appendLine("            ${nativeGroup(path, g)},")
            appendLine("        ),")
        }
        appendLine("    )")
        appendLine()
        appendLine("    private val ownFields = mapOf<List<String>, List<Pair<String, String>>>(")
        for (c in m.commands) {
            val own = c.canonicalOwn().joinToString(", ") { "${lit(it.name)} to ${it.registeredWit(it.typeDesc, R)}" }
            appendLine("        listOf(${lit(c.path.single())}) to listOf($own),")
        }
        appendLine("    )")
        appendLine()
        appendLine("    /** The input record of the direct command [command]: the [globals] of its enclosing groups, then its own values in canonical order. */")
        appendLine("    fun input(command: List<String>, globals: List<$R.ToolInputField>, vararg own: SchemaValue): $R.TypedSchemaValue =")
        appendLine("        $R.toolInput(globals, ownFields.getValue(command), own.toList())")
        for (e in m.directErrorClasses()) {
            appendLine()
            appendLine("    fun decode${e.simpleName}(name: String, payload: $R.TypedSchemaValue): ${e.qualifiedName}? = when (name) {")
            for (case in e.cases) {
                val value = when {
                    case.fields.size == 1 -> "${case.className}(${ConverterCodegen.decode(case.fields[0].typeDesc, "payload.value")})"
                    else -> case.payloadTypeDesc?.let { ConverterCodegen.decode(it, "payload.value") } ?: if (case.isObject) case.className else "${case.className}()"
                }
                appendLine("        ${lit(case.kebabName)} -> $value")
            }
            appendLine("        else -> null")
            appendLine("    }")
            appendLine()
            appendLine("    fun encode${e.simpleName}(e: ${e.qualifiedName}): $R.ToolError.CustomError = when (e) {")
            for (case in e.cases) {
                val payload = case.payloadTypeDesc?.let {
                    val source = if (case.fields.size == 1) "e.${case.fields[0].name}" else "e"
                    "$R.TypedSchemaValue(${lit(it.toWit())}, ${ConverterCodegen.encode(it, source)})"
                }
                    ?: "$R.TypedSchemaValue(\"tuple<>\", SchemaValue.TupleVal(emptyList()))"
                appendLine("        is ${case.className} -> $R.ToolError.CustomError(${lit(case.kebabName)}, $payload)")
            }
            appendLine("    }")
        }
        appendLine("}")
    }

    private fun client(m: ToolDefinitionModel): String = buildString {
        val x = m.interfaceName
        appendLine("/** Typed calls to the tool ${doc(m.name)}. */")
        appendLine("class ${x}Client(private val golemRpc: $R.ToolRpc, private val golemPrefix: List<String> = emptyList(), private val golemGlobals: List<$R.ToolInputField> = emptyList()) {")
        for (c in m.commands) {
            appendLine("    fun ${c.methodName}(${params(c, stdinParam(c, "kotlin.ByteArray"))}): ${returnType(c)} =")
            appendLine("        golemRpc.${callName(c)}(golemPrefix + ${pathLit(c.path)}, ${inputExpr(m, c)}, ${stdinArg(c)}${captureArgs(c)}${errorDecoder(m, c)}) ${resultDecoder(c)}")
        }
        for (g in m.groups) {
            val child = "${g.child.packageName}.${g.child.interfaceName}Client"
            appendLine("    fun ${g.methodName}(${groupParams(g)}): $child = $child(golemRpc, golemPrefix + listOf(${lit(g.kebabName)}), golemGlobals + ${globalFields(g)})")
        }
        appendLine("}")
    }

    private fun underlying(m: ToolDefinitionModel): String = buildString {
        val x = m.interfaceName
        appendLine("/** The wrapped tool ${doc(m.name)} as a middleware sees it; valid only while the middleware handles the invocation. The host supplies the principal of the call. */")
        appendLine("class ${x}Underlying(private val golemUnder: $R.ToolCaller, private val golemPrefix: List<String> = emptyList(), private val golemGlobals: List<$R.ToolInputField> = emptyList()) {")
        for (c in m.commands) {
            appendLine("    fun ${c.methodName}(${params(c, stdinParam(c, "$R.ToolStdin"))}): ${returnType(c)} =")
            appendLine("        golemUnder.${callName(c)}(golemPrefix + ${pathLit(c.path)}, ${inputExpr(m, c)}, ${stdinArg(c)}${errorDecoder(m, c)}) ${resultDecoder(c)}")
        }
        for (c in m.commands) {
            val typed = if (c.hasOutputs) "TypedInvocationWithOutputs" else "TypedInvocation"
            appendLine("    fun start${c.methodName.replaceFirstChar { it.uppercase() }}(${params(c, stdinParam(c, "$R.ToolStdin"))}): $R.$typed<${c.errorClass?.qualifiedName ?: "Nothing"}, ${c.outputKotlinType}> =")
            appendLine("        $R.$typed(golemUnder.start(golemPrefix + ${pathLit(c.path)}, ${inputExpr(m, c)}, ${if (c.stdin) "stdin" else "null"}), ${errorDecoder(m, c)}) ${resultDecoder(c)}")
        }
        for (g in m.groups) {
            val child = "${g.child.packageName}.${g.child.interfaceName}Underlying"
            appendLine("    fun ${g.methodName}(${groupParams(g)}): $child = $child(golemUnder, golemPrefix + listOf(${lit(g.kebabName)}), golemGlobals + ${globalFields(g)})")
        }
        appendLine("}")
    }

    private fun middleware(m: ToolDefinitionModel): String = buildString {
        val x = m.interfaceName
        appendLine("/** Base class of a transparent middleware for ${doc(m.name)}: every command forwards to the wrapped tool unless overridden. */")
        appendLine("abstract class ${x}Middleware : $R.TypedToolMiddleware<${x}Underlying>() {")
        for (c in m.flatCommands()) {
            val sig = (listOf("underlying: ${x}Underlying") + c.signature().map { "${it.first}: ${it.second}" } + handlerStdin(c)).joinToString(", ")
            val chain = c.groupChain.indices.joinToString("") { ".${c.groupChain[it]}(${c.groupArgs[it].joinToString(", ") { a -> a.paramName }})" }
            val call = "underlying$chain.${c.methodName}(${(c.params.map { it.name } + (if (c.stdin) listOf("stdin") else emptyList())).joinToString(", ")})"
            appendLine("    open fun ${c.handlerName}($sig): ${returnType(c)} =")
            appendLine("        $call")
        }
        appendLine("}")
    }

    private fun adapter(m: ToolDefinitionModel): String = buildString {
        val x = m.interfaceName
        appendLine("/** Base class of an adapter that presents ${doc(m.name)} on top of another tool [U]: every command must be handled. */")
        appendLine("abstract class ${x}Adapter<U : Any> : $R.TypedToolMiddleware<U>() {")
        for (c in m.flatCommands()) {
            val sig = (listOf("underlying: U") + c.signature().map { "${it.first}: ${it.second}" } + handlerStdin(c)).joinToString(", ")
            appendLine("    abstract fun ${c.handlerName}($sig): ${returnType(c)}")
        }
        appendLine("}")
    }

    private fun returnType(c: ToolCommandModel): String {
        val value = if (c.hasOutputs) "$R.WithOutputs<${c.outputKotlinType}>" else c.outputKotlinType
        return "$R.Either<$R.ToolInvokeError<${c.errorClass?.qualifiedName ?: "Nothing"}>, $value>"
    }

    private fun stdinParam(c: ToolCommandModel, type: String): String? = if (c.stdin) "stdin: $type? = null" else null

    private fun stdinArg(c: ToolCommandModel): String = if (c.stdin) {
        "stdin, "
    } else if (c.hasOutputs) {
        "null, "
    } else {
        ""
    }

    private fun captureArgs(c: ToolCommandModel): String = if (c.hasOutputs) "${c.stdout}, ${c.stderr}, " else ""

    private fun callName(c: ToolCommandModel): String = if (c.hasOutputs) "callTypedWithOutputs" else "callTyped"

    private fun handlerStdin(c: ToolCommandModel): List<String> = if (c.stdin) listOf("stdin: $R.ToolStdin?") else emptyList()

    private fun pathLit(path: List<String>): String = "listOf(${path.joinToString(", ") { lit(it) }})"

    private fun params(c: ToolCommandModel, extra: String? = null): String = (c.params.indices.map { "${c.params[it].name}: ${c.paramKotlinTypes[it]}" } + listOfNotNull(extra)).joinToString(", ")

    private fun groupParams(g: ToolGroupModel): String = g.args.joinToString(", ") { "${it.paramName}: ${it.kotlinType}" }

    private fun inputField(a: ToolArgModel): String = "$R.ToolInputField(${lit(a.name)}, ${a.registeredWit(a.typeDesc, R)}, ${ConverterCodegen.encode(a.typeDesc, a.paramName)})"

    private fun globalFields(g: ToolGroupModel): String = "listOf(${g.canonicalArgs.joinToString(", ") { inputField(it) }})"

    private fun inputExpr(m: ToolDefinitionModel, c: ToolCommandModel): String {
        val values = c.canonicalOwn().joinToString(", ") { ConverterCodegen.encode(it.typeDesc, it.paramName) }
        return "${m.interfaceName}Definition.input(${pathLit(c.path)}, golemGlobals${if (values.isEmpty()) "" else ", $values"})"
    }

    private fun allGroups(m: ToolDefinitionModel, prefix: List<String>): List<Pair<List<String>, ToolGroupModel>> = m.groups.flatMap { g -> listOf((prefix + g.kebabName) to g) + allGroups(g.child, prefix + g.kebabName) }

    private fun nativeGroup(path: List<String>, g: ToolGroupModel): String {
        val options = g.args.filter { !it.isFlag }.joinToString(", ") { nativeArg(it) }
        val flags = g.args.filter { it.isFlag }.joinToString(", ") { nativeArg(it) }
        return "$R.NativeGroup(${pathLit(path)}, ${lit(g.description)}, ${strings(g.aliases)}, listOf($options), listOf($flags))"
    }

    private fun nativeCommand(c: ToolCommandModel): String {
        val positionals = c.args.filter { it.kind == ToolArgKind.POSITIONAL }.joinToString(", ") {
            "$R.NativeToolParamSchema(${lit(it.name)}, ${it.registeredWit(it.typeDesc, R)}, ${lit(it.doc)}, ${it.valueName?.let { v -> lit(v) } ?: "null"}, ${it.acceptsStdio})"
        }
        val errors = c.errorClass?.cases?.joinToString(", ") {
            "$R.NativeToolErrorCase(${lit(it.kebabName)}, ${lit(it.description)}, ${it.payloadWitType?.let { w -> lit(w) } ?: "null"}, ${it.usage}, ${it.exitCode})"
        }
        val tail = c.args.firstOrNull { it.kind == ToolArgKind.TAIL }?.let { nativeArg(it) } ?: "null"
        val options = c.args.filter { it.kind == ToolArgKind.OPTION }.joinToString(", ") { nativeArg(it) }
        val flags = c.args.filter { it.isFlag }.joinToString(", ") { nativeArg(it) }
        val constraints = c.constraints.joinToString(", ") { constraint(it) }
        val hints = c.hints?.let { "$R.ToolAnnotationsInfo(${it.readOnly}, ${it.destructive}, ${it.idempotent}, ${it.openWorld})" } ?: "null"
        val examples = c.examples.joinToString(", ") { "$R.ToolExample(${lit(it.first)}, ${lit(it.second)})" }
        val extras = "$R.NativeBodyExtras(tail = $tail, options = listOf($options), flags = listOf($flags), constraints = listOf($constraints), " +
            "formatters = ${strings(c.formatters)}, defaultFormatter = ${lit(c.defaultFormatter)}, annotations = $hints, " +
            "stdin = ${c.stdin}, stdout = ${c.stdout}, stderr = ${c.stderr})"
        return "$R.NativeCommand(${pathLit(c.path)}, ${lit(c.description)}, listOf($positionals), ${lit(c.outputTypeDesc.toWit())}, " +
            "${if (errors == null) "emptyList()" else "listOf($errors)"}, ${strings(c.aliases)}, listOf($examples), $extras)"
    }

    private fun nativeArg(a: ToolArgModel): String {
        val shape = when {
            a.kind == ToolArgKind.TAIL -> "$R.NativeArgShape.Tail(${a.minItems}, ${a.maxItems ?: "null"}, ${a.separator?.let { lit(it) } ?: "null"}, ${a.verbatim}, ${a.acceptsStdio})"
            a.kind == ToolArgKind.FLAG -> "$R.NativeArgShape.BoolFlag(${a.flagDefault}, ${a.negatable})"
            a.kind == ToolArgKind.COUNT_FLAG -> "$R.NativeArgShape.CountFlag(${a.maxItems ?: "null"})"
            a.shape == ToolOptionShape.OPTIONAL_SCALAR -> "$R.NativeArgShape.OptionalScalar"
            a.shape == ToolOptionShape.REPEATABLE_LIST -> {
                val d = a.delimiter?.code
                "$R.NativeArgShape.RepeatableList(" + when (a.repetition) {
                    "DELIMITED" -> "$R.NativeRepetition.Delimited($d)"
                    "EITHER" -> "$R.NativeRepetition.Either($d)"
                    else -> "$R.NativeRepetition.Repeated"
                } + ")"
            }
            else -> "$R.NativeArgShape.Scalar"
        }
        return "$R.NativeArg(${lit(a.name)}, $shape, ${a.nodeTypeDesc?.let { a.registeredWit(it, R) } ?: "null"}, ${lit(a.doc)}, ${a.valueName?.let { lit(it) } ?: "null"}, " +
            "${a.short?.code ?: "null"}, ${strings(a.aliases)}, ${a.env?.let { lit(it) } ?: "null"}, ${a.defaultExpr ?: "null"})"
    }

    private fun refs(refs: List<ToolRefModel>): String = "listOf(${refs.joinToString(", ") { "$R.ToolRef(${lit(it.name)}, ${it.valueExpr ?: "null"})" }})"

    private fun constraint(c: ToolConstraintModel): String = when (c) {
        is ToolConstraintModel.RequiresAll -> "$R.ToolConstraint.RequiresAll(${refs(c.refs)})"
        is ToolConstraintModel.RequiresAny -> "$R.ToolConstraint.RequiresAny(${refs(c.refs)})"
        is ToolConstraintModel.AllOrNone -> "$R.ToolConstraint.AllOrNone(${refs(c.refs)})"
        is ToolConstraintModel.MutexGroups -> "$R.ToolConstraint.MutexGroups(listOf(${c.groups.joinToString(", ") { refs(it) }}))"
        is ToolConstraintModel.Implies -> "$R.ToolConstraint.Implies(${c.lhsAny}, ${refs(c.lhs)}, ${c.rhsAny}, ${refs(c.rhs)})"
        is ToolConstraintModel.Forbids -> "$R.ToolConstraint.Forbids(${c.lhsAny}, ${refs(c.lhs)}, ${refs(c.rhs)})"
    }

    private fun strings(values: List<String>): String = if (values.isEmpty()) "emptyList()" else "listOf(${values.joinToString(", ") { lit(it) }})"

    private fun errorDecoder(m: ToolDefinitionModel, c: ToolCommandModel): String = c.errorClass?.let { "${m.interfaceName}Definition::decode${it.simpleName}" } ?: "::noDeclaredErrorDecoder"

    private fun resultDecoder(c: ToolCommandModel): String = if (c.outputTypeDesc is TypeDesc.UnitT) "{ _ -> Unit }" else "{ golemSv -> ${ConverterCodegen.decode(c.outputTypeDesc, "golemSv!!")} }"

    private fun doc(s: String): String = "\"" + s.replace("*/", "* /") + "\""

    private fun lit(s: String): String = kotlinStringLiteral(s)
}
