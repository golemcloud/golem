package cloud.golem.ksp

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies

private const val R = "cloud.golem.runtime"

/** Generates `golemProvide<Class>`: the [R].NativeToolProvider that decodes a command's input, calls the implementation and encodes its result. */
class ToolProviderEmitter(private val codeGenerator: CodeGenerator) {

    fun factoryName(model: ToolProviderModel): String = "golemProvide${model.qualifiedName.removePrefix("${model.packageName}.").replace('.', '_')}"

    fun emit(model: ToolProviderModel) {
        val factory = factoryName(model)
        val code = buildString {
            appendLine("// AUTO-GENERATED by golem-kotlin-ksp — do not edit")
            appendLine("package ${model.packageName}")
            appendLine()
            appendLine("import $R.SchemaValue")
            appendLine("import $R.noDeclaredErrorEncoder")
            appendLine()
            appendLine("fun $factory(): $R.NativeToolProvider = $R.NativeToolProvider(${model.definition.packageName}.${model.definition.interfaceName}Definition.tool) { commandPath, input, principal ->")
            appendLine("    val impl = ${model.qualifiedName}()")
            appendLine("    when (commandPath) {")
            for (c in model.definition.flatCommands()) {
                appendLine("        listOf(${c.path.joinToString(", ") { lit(it) }}) -> ${command(c)}")
            }
            appendLine("        else -> $R.ToolMiddlewareOutcome.Err($R.ToolError.InvalidCommandPath(commandPath))")
            appendLine("    }")
            appendLine("}")
        }
        codeGenerator.createNewFile(
            dependencies = Dependencies.ALL_FILES,
            packageName = model.packageName,
            fileName = factory,
            extensionName = "kt",
        ).bufferedWriter().use { it.write(code) }
    }

    private fun command(c: ToolCommandModel): String {
        val errorType = c.errorClass?.qualifiedName ?: "Nothing"
        val encodeError = c.errorClass?.let { "${c.definitionFqn}::encode${it.simpleName}" } ?: "::noDeclaredErrorEncoder"
        val encodeResult = if (c.outputTypeDesc is TypeDesc.UnitT) "{ SchemaValue.Unit_ }" else "{ ${ConverterCodegen.encode(c.outputTypeDesc, "it")} }"
        val canonical = c.canonicalArgs
        val decodes = ArrayList<String>()
        val locals = HashMap<String, String>()
        canonical.forEachIndexed { index, a ->
            val local = "golemArg$index"
            decodes.add("val $local = ${ConverterCodegen.decode(a.typeDesc, "args[$index]")}; ")
            locals[a.paramName] = local
        }
        fun value(name: String): String = if (name == c.principalName) "principal" else locals.getValue(name)
        val chain = c.groupChain.indices.joinToString("") { ".${c.groupChain[it]}(${c.groupArgs[it].joinToString(", ") { a -> value(a.paramName) }})" }
        val call = "impl$chain.${c.methodName}(${c.ownSignature().joinToString(", ") { value(it.first) }})"
        val outcome = if (c.errorClass == null) {
            "$R.Either.Right($call)"
        } else {
            "when (val golemOut = $call) { is $R.Either.Left -> $R.Either.Left($R.ToolInvokeError.Tool(golemOut.value)); is $R.Either.Right -> $R.Either.Right(golemOut.value) }"
        }
        return "$R.dispatchTyped<$errorType, ${c.outputKotlinType}>(input, ${canonical.size}, ${lit(c.outputTypeDesc.toWit())}, " +
            "$encodeError, $encodeResult) { ${if (decodes.isEmpty()) "_" else "args"} -> ${decodes.joinToString("")}{ $outcome } }"
    }

    private fun lit(s: String): String = kotlinStringLiteral(s)
}
