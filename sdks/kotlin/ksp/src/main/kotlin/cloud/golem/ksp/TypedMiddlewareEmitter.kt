package cloud.golem.ksp

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies

private const val R = "cloud.golem.runtime"

/**
 * What a `@ToolMiddleware` subclass of a generated `XMiddleware` / `XAdapter<Y>` presents and wraps. [expected] is `null` for a transparent
 * middleware (it wraps the tool it presents).
 */
data class TypedMiddlewareBinding(val presented: ToolDefinitionModel, val expected: ToolDefinitionModel?)

/** Generates `<Class>Dispatch`: the [R].UniversalToolMiddleware that decodes a command's input, calls the typed handler and encodes its result. */
class TypedMiddlewareEmitter(private val codeGenerator: CodeGenerator) {

    fun dispatchClassName(model: ToolMiddlewareModel): String = "${model.qualifiedName.removePrefix("${model.packageName}.").replace('.', '_')}Dispatch"

    fun emit(model: ToolMiddlewareModel, binding: TypedMiddlewareBinding) {
        val dispatch = dispatchClassName(model)
        val underlyingType = (binding.expected ?: binding.presented).let { "${it.packageName}.${it.interfaceName}Underlying" }
        val code = buildString {
            appendLine("// AUTO-GENERATED by golem-kotlin-ksp — do not edit")
            appendLine("package ${model.packageName}")
            appendLine()
            appendLine("import $R.SchemaValue")
            appendLine("import $R.noDeclaredErrorEncoder")
            appendLine()
            appendLine("internal class $dispatch(private val mw: ${model.qualifiedName}) : $R.UniversalToolMiddleware {")
            appendLine("    override fun invoke(invocation: $R.ToolMiddlewareInvocation, underlying: $R.ToolUnderlying): $R.ToolMiddlewareOutcome {")
            appendLine("        mw.bind(invocation)")
            appendLine("        val golemUnder = $underlyingType(underlying)")
            appendLine("        return when (invocation.commandPath) {")
            for (c in binding.presented.flatCommands()) {
                appendLine("            listOf(${c.path.joinToString(", ") { lit(it) }}) -> ${command(c)}")
            }
            appendLine("            else -> $R.ToolMiddlewareOutcome.Err($R.ToolError.InvalidCommandPath(invocation.commandPath))")
            appendLine("        }")
            appendLine("    }")
            appendLine("}")
        }
        codeGenerator.createNewFile(
            dependencies = Dependencies.ALL_FILES,
            packageName = model.packageName,
            fileName = dispatch,
            extensionName = "kt",
        ).bufferedWriter().use { it.write(code) }
    }

    private fun command(c: ToolCommandModel): String {
        val errorType = c.errorClass?.qualifiedName ?: "Nothing"
        val encodeError = c.errorClass?.let { "${c.definitionFqn}::encode${it.simpleName}" } ?: "::noDeclaredErrorEncoder"
        val encodeResult = if (c.outputTypeDesc is TypeDesc.UnitT) "{ SchemaValue.Unit_ }" else "{ ${ConverterCodegen.encode(c.outputTypeDesc, "it")} }"
        val canonical = c.canonicalArgs
        val decodes = ArrayList<String>()
        val args = c.signature().joinToString(", ") { (name, _) ->
            if (name == c.principalName) {
                "invocation.principal"
            } else {
                val index = canonical.indexOfFirst { it.paramName == name }
                val local = "golemArg$index"
                decodes.add("val $local = ${ConverterCodegen.decode(canonical[index].typeDesc, "args[$index]")}; ")
                local
            }
        }
        val handlerArgs = listOf("golemUnder", args, if (c.stdin) "invocation.stdin" else "").filter { it.isNotEmpty() }.joinToString(", ")
        val dispatch = if (c.hasOutputs) "dispatchTypedWithOutputs" else "dispatchTyped"
        return "$R.$dispatch<$errorType, ${c.outputKotlinType}>(invocation.input, ${canonical.size}, ${lit(c.outputTypeDesc.toWit())}, " +
            "$encodeError, $encodeResult) { ${if (decodes.isEmpty()) "_" else "args"} -> ${decodes.joinToString("")}{ mw.${c.handlerName}($handlerArgs) } }"
    }

    private fun lit(s: String): String = kotlinStringLiteral(s)
}
