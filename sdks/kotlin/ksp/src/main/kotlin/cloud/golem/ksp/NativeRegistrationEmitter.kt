package cloud.golem.ksp

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies

/**
 * Generates the native (Kotlin/Wasm) registration + `@WasmExport` entry points.
 *
 * The agent is compiled against `golem-kotlin-sdk` as a normal Kotlin/Wasm dependency, so the
 * generated code uses the SDK's real `NativeAgentDescriptor`/`SchemaValue` types directly.
 *
 * Two outputs:
 *  - `<ClassName>Registration.kt` : `fun register<ClassName>()` per `@Agent` class, calling
 *    `NativeAgentRuntime.registerAgent(typeName) { NativeAgentDescriptor(...) }` with handler/factory lambdas
 *    that read `List<SchemaValue>` (via `.asString()`/`.asInt()`) and return a `SchemaValue`.
 *  - `GolemGeneratedGuest.kt` : the actual `@WasmExport("golem:agent/guest@2.0.0#...")` functions.
 *
 * WHY the wrappers live here, not in the SDK's `Guest.kt` (see that file's doc comment for the
 * full rationale): a Kotlin/Wasm reactor component does not run top-level `val` initializers
 * automatically at instantiation, and unreferenced top-level code is dead-code-eliminated -- so
 * agent registration (which the SDK cannot see ahead of time) needs a guaranteed-reachable
 * trigger. Generating the real `@WasmExport` functions here guarantees a call to
 * `registerAllAgents()` happens before any SDK logic runs, because the host is contractually
 * required to call these exports to talk to the agent at all.
 */
class NativeRegistrationEmitter(private val codeGenerator: CodeGenerator) {

    /** Per-agent registration function. */
    fun emit(model: AgentModel) {
        val code = buildString {
            appendLine("// AUTO-GENERATED by golem-kotlin-ksp — do not edit")
            appendLine("package ${model.packageName}")
            appendLine()
            appendLine("import cloud.golem.runtime.NativeAgentRuntime")
            appendLine("import cloud.golem.runtime.NativeAgentDescriptor")
            appendLine("import cloud.golem.runtime.NativeMethodDescriptor")
            appendLine("import cloud.golem.runtime.NativeParamSchema")
            appendLine("import cloud.golem.runtime.NativeHttpEndpoint")
            appendLine("import cloud.golem.runtime.SchemaValue")
            appendLine()
            appendLine("fun register${model.className}() {")
            appendLine("    NativeAgentRuntime.registerAgent(${lit(model.typeName)}) {")
            appendLine("        NativeAgentDescriptor(")
            appendLine("            ${lit(model.typeName)},")
            appendLine("            ${lit(model.classDescription)},")
            appendLine("            ${lit(model.mountPath)},")
            appendLine("            ${paramSchemaList(model.constructorParams)},")
            appendLine("            listOf(")
            model.methods.forEachIndexed { i, m ->
                val comma = if (i < model.methods.size - 1) "," else ""
                appendLine("                ${methodDescriptor(model.className, m)}$comma")
            }
            appendLine("            ),")
            appendLine("            ${factoryLambda(model)},")
            appendLine("            ${model.mountAuth},")
            appendLine("            ${corsList(model.mountCors)},")
            appendLine("            ${lit(model.mode)},")
            append("            ${lit(model.snapshotting)}")
            append(snapshotArg(model))
            append(configArg(model))
            appendLine(httpArgs(model))
            appendLine("        )")
            appendLine("    }")
            appendLine("}")
        }
        write(model.packageName, "${model.className}Registration", code)
    }

    /** Single entry point: idempotent registration + the real @WasmExport guest functions. */
    fun emitEntryPoint(models: List<AgentModel>, tools: List<ToolModel> = emptyList(), middlewares: List<ToolMiddlewareModel> = emptyList(), providers: List<ToolProviderModel> = emptyList(), arenaHeadroomBytes: Int? = null) {
        val pkg = models.firstOrNull()?.packageName ?: tools.firstOrNull()?.packageName ?: middlewares.firstOrNull()?.packageName ?: providers.first().packageName
        val code = buildString {
            appendLine("// AUTO-GENERATED by golem-kotlin-ksp — do not edit")
            appendLine("package $pkg")
            appendLine()
            appendLine("import cloud.golem.runtime.SchemaValue")
            appendLine("import kotlin.wasm.WasmExport")
            appendLine()
            // cabi_realloc must be declared HERE (the agent's own module), not in the SDK: a
            // Kotlin/Wasm library dependency's @WasmExport declarations do not survive into the
            // consuming executable's final linked module (verified empirically -- the same
            // cross-module DCE limitation as the golem:agent/guest exports below).
            // A component that sets `golem.arenaHeadroomKiB` has the headroom set before the arena is first used, however the
            // guest is entered: at module start, in cabi_realloc, and at the top of every registration function.
            val setHeadroom = arenaHeadroomBytes?.let { "cloud.golem.wasm.configureArenaHeadroom($it)" }
            if (setHeadroom != null) {
                appendLine("private val golemArenaHeadroom = $setHeadroom")
                appendLine()
            }
            appendLine("@WasmExport(\"cabi_realloc\")")
            if (setHeadroom == null) {
                appendLine("fun golemGuestCabiRealloc(oldPtr: Int, oldSize: Int, align: Int, newSize: Int): Int =")
                appendLine("    cloud.golem.wasm.cabiRealloc(oldPtr, oldSize, align, newSize)")
            } else {
                appendLine("fun golemGuestCabiRealloc(oldPtr: Int, oldSize: Int, align: Int, newSize: Int): Int {")
                appendLine("    $setHeadroom")
                appendLine("    return cloud.golem.wasm.cabiRealloc(oldPtr, oldSize, align, newSize)")
                appendLine("}")
            }
            appendLine()
            appendLine("private var golemAgentsRegistered = false")
            appendLine()
            appendLine("fun registerAllAgents() {")
            if (setHeadroom != null) appendLine("    $setHeadroom")
            appendLine("    if (golemAgentsRegistered) return")
            appendLine("    golemAgentsRegistered = true")
            models.forEach { m ->
                appendLine("    ${m.packageName}.register${m.className}()")
            }
            appendLine("}")
            appendLine()
            appendLine("private var golemToolsRegistered = false")
            appendLine()
            appendLine("fun registerAllTools() {")
            if (setHeadroom != null) appendLine("    $setHeadroom")
            appendLine("    if (golemToolsRegistered) return")
            appendLine("    golemToolsRegistered = true")
            tools.forEach { t -> appendLine("    ${toolRegistration(t)}") }
            providers.forEach { p -> appendLine("    cloud.golem.runtime.NativeToolRuntime.registerProvider(${p.packageName}.${ToolProviderEmitter(codeGenerator).factoryName(p)}())") }
            appendLine("}")
            appendLine()
            appendLine("private var golemMiddlewaresRegistered = false")
            appendLine()
            appendLine("fun registerAllToolMiddlewares() {")
            if (setHeadroom != null) appendLine("    $setHeadroom")
            appendLine("    if (golemMiddlewaresRegistered) return")
            appendLine("    golemMiddlewaresRegistered = true")
            middlewares.forEach { m ->
                val witType = m.parameterDesc?.toWit() ?: "record<>"
                val decoder = m.parameterDesc?.let { ", { sv -> ${decode(it, "sv")} }" } ?: ""
                val typed = m.typed
                val create = if (typed == null) "${m.qualifiedName}()" else "${m.packageName}.${TypedMiddlewareEmitter(codeGenerator).dispatchClassName(m)}(${m.qualifiedName}())"
                val scope = typed?.let {
                    ", scope = cloud.golem.runtime.MiddlewareScope.Monomorphic(${it.presented.definitionFqn}.tool, ${it.expected?.let { e -> "${e.definitionFqn}.tool" } ?: "null"})"
                } ?: ""
                appendLine(
                    "    cloud.golem.runtime.NativeToolMiddlewareRuntime.register(cloud.golem.runtime.NativeToolMiddlewareDescriptor(" +
                        "${lit(m.name)}, ${lit(m.version)}, ${aliasList(m.aliases)}, ${lit(m.description)}, ${lit(witType)}, { $create }$decoder$scope))",
                )
            }
            appendLine("}")
            appendLine()
            // The world exports golem:tool/tool-middleware-guest, so these exist even with no @ToolMiddleware (empty registry).
            appendLine("@WasmExport(\"golem:tool/tool-middleware-guest@0.1.0#discover-tool-middlewares\")")
            appendLine("fun golemMiddlewareDiscover(): Int {")
            appendLine("    registerAllToolMiddlewares()")
            appendLine("    return cloud.golem.runtime.discoverToolMiddlewares()")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:tool/tool-middleware-guest@0.1.0#discover-tool-middlewares\")")
            appendLine("fun golemMiddlewareCabiPostDiscover(resultPtr: Int) { cloud.golem.runtime.cabiPostDiscoverToolMiddlewares(resultPtr) }")
            appendLine()
            appendLine("@WasmExport(\"golem:tool/tool-middleware-guest@0.1.0#get-tool-middleware\")")
            appendLine("fun golemMiddlewareGet(namePtr: Int, nameLen: Int): Int {")
            appendLine("    registerAllToolMiddlewares()")
            appendLine("    return cloud.golem.runtime.getToolMiddleware(namePtr, nameLen)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:tool/tool-middleware-guest@0.1.0#get-tool-middleware\")")
            appendLine("fun golemMiddlewareCabiPostGet(resultPtr: Int) { cloud.golem.runtime.cabiPostGetToolMiddleware(resultPtr) }")
            appendLine()
            appendLine("@WasmExport(\"golem:tool/tool-middleware-guest@0.1.0#invoke-tool-middleware\")")
            appendLine("fun golemMiddlewareInvoke(argsPtr: Int): Int {")
            appendLine("    registerAllToolMiddlewares()")
            appendLine("    return cloud.golem.runtime.invokeToolMiddleware(argsPtr)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:tool/tool-middleware-guest@0.1.0#invoke-tool-middleware\")")
            appendLine("fun golemMiddlewareCabiPostInvoke(resultPtr: Int) { cloud.golem.runtime.cabiPostInvokeToolMiddleware(resultPtr) }")
            appendLine()
            appendLine("@WasmExport(\"golem:agent/guest@2.0.0#initialize\")")
            appendLine("fun golemGuestInitialize(argsPtr: Int): Int {")
            appendLine("    registerAllAgents()")
            appendLine("    return cloud.golem.runtime.initialize(argsPtr)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:agent/guest@2.0.0#initialize\")")
            appendLine("fun golemGuestCabiPostInitialize(resultPtr: Int) {")
            appendLine("    cloud.golem.runtime.cabiPostInitialize(resultPtr)")
            appendLine("}")
            appendLine()
            // `invoke` is exported async-lifted (with the mandatory, never-used callback): it delivers its result with task.return and
            // may keep running afterwards. Returning 0 = EXIT.
            appendLine("@WasmExport(\"[async-lift]golem:agent/guest@2.0.0#invoke\")")
            appendLine("fun golemGuestInvoke(argsPtr: Int): Int {")
            appendLine("    registerAllAgents()")
            appendLine("    cloud.golem.runtime.invokeAsync(argsPtr)")
            appendLine("    return 0")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"[callback][async-lift]golem:agent/guest@2.0.0#invoke\")")
            appendLine("fun golemGuestInvokeCallback(event: Int, payload1: Int, payload2: Int): Int = 0")
            appendLine()
            appendLine("@WasmExport(\"golem:agent/guest@2.0.0#get-definition\")")
            appendLine("fun golemGuestGetDefinition(): Int {")
            appendLine("    registerAllAgents()")
            appendLine("    return cloud.golem.runtime.getDefinition()")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:agent/guest@2.0.0#get-definition\")")
            appendLine("fun golemGuestCabiPostGetDefinition(resultPtr: Int) {")
            appendLine("    cloud.golem.runtime.cabiPostGetDefinition(resultPtr)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"golem:agent/guest@2.0.0#discover-agent-types\")")
            appendLine("fun golemGuestDiscoverAgentTypes(): Int {")
            appendLine("    registerAllAgents()")
            appendLine("    return cloud.golem.runtime.discoverAgentTypes()")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:agent/guest@2.0.0#discover-agent-types\")")
            appendLine("fun golemGuestCabiPostDiscoverAgentTypes(resultPtr: Int) {")
            appendLine("    cloud.golem.runtime.cabiPostDiscoverAgentTypes(resultPtr)")
            appendLine("}")
            appendLine()
            // wit-native's shared world always includes golem:tool/tool-guest@0.1.0 (component
            // embed requires every world export to exist), so these are emitted unconditionally
            // -- even a project with zero @Tool-annotated methods needs a (functionally empty)
            // tool interface. With no @Tool functions the registry stays empty (discover-tools ->
            // ok([]), get-tool/invoke -> "unknown tool" errors). `@Tool` functions are registered by
            // registerAllTools(), which each tool export calls first (the host may call discover-tools
            // before anything else, and Kotlin/Wasm does not run top-level initializers on its own).
            appendLine("@WasmExport(\"golem:tool/guest@0.1.0#discover-tools\")")
            appendLine("fun golemToolDiscoverTools(): Int {")
            appendLine("    registerAllTools()")
            appendLine("    return cloud.golem.runtime.discoverTools()")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:tool/guest@0.1.0#discover-tools\")")
            appendLine("fun golemToolCabiPostDiscoverTools(resultPtr: Int) {")
            appendLine("    cloud.golem.runtime.cabiPostDiscoverTools(resultPtr)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"golem:tool/guest@0.1.0#get-tool\")")
            appendLine("fun golemToolGetTool(namePtr: Int, nameLen: Int): Int {")
            appendLine("    registerAllTools()")
            appendLine("    return cloud.golem.runtime.getTool(namePtr, nameLen)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:tool/guest@0.1.0#get-tool\")")
            appendLine("fun golemToolCabiPostGetTool(resultPtr: Int) {")
            appendLine("    cloud.golem.runtime.cabiPostGetTool(resultPtr)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"golem:tool/guest@0.1.0#invoke\")")
            appendLine("fun golemToolInvoke(argsPtr: Int): Int {")
            appendLine("    registerAllTools()")
            appendLine("    return cloud.golem.runtime.invokeTool(argsPtr)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:tool/guest@0.1.0#invoke\")")
            appendLine("fun golemToolCabiPostInvoke(resultPtr: Int) {")
            appendLine("    cloud.golem.runtime.cabiPostInvokeTool(resultPtr)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"golem:api/save-snapshot@1.5.0#save\")")
            appendLine("fun golemSaveSnapshot(): Int {")
            appendLine("    registerAllAgents()")
            appendLine("    return cloud.golem.runtime.saveSnapshot()")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:api/save-snapshot@1.5.0#save\")")
            appendLine("fun golemCabiPostSaveSnapshot(resultPtr: Int) {")
            appendLine("    cloud.golem.runtime.cabiPostSaveSnapshot(resultPtr)")
            appendLine("}")
            appendLine()
            // Canonical ABI flattens record { payload: list<u8>, mime-type: string } into
            // four I32 params; wasm-tools component embed expects [I32,I32,I32,I32] -> [I32].
            appendLine("@WasmExport(\"golem:api/load-snapshot@1.5.0#load\")")
            appendLine("fun golemLoadSnapshot(payloadPtr: Int, payloadLen: Int, mimeTypePtr: Int, mimeTypeLen: Int): Int {")
            appendLine("    registerAllAgents()")
            appendLine("    return cloud.golem.runtime.loadSnapshotFlat(payloadPtr, payloadLen, mimeTypePtr, mimeTypeLen)")
            appendLine("}")
            appendLine()
            appendLine("@WasmExport(\"cabi_post_golem:api/load-snapshot@1.5.0#load\")")
            appendLine("fun golemCabiPostLoadSnapshot(resultPtr: Int) {")
            appendLine("    cloud.golem.runtime.cabiPostLoadSnapshot(resultPtr)")
            appendLine("}")
        }
        write(pkg, "GolemGeneratedGuest", code)
    }

    // -- code generation -----------------------------------------------------

    /** `NativeToolRuntime.registerTool(NativeToolDescriptor(...))` for one `@Tool` function. */
    private fun toolRegistration(t: ToolModel): String {
        val params = if (t.params.isEmpty()) {
            "emptyList()"
        } else {
            "listOf(${t.params.joinToString(", ") { "cloud.golem.runtime.NativeToolParamSchema(${lit(it.name)}, ${lit(it.witType)})" }})"
        }
        // Positional values come from `input` in order; the ToolStreams parameter (if any) is spliced in at its position.
        val values = t.params.mapIndexed { i, p -> decode(p.typeDesc, "input[$i]") }.toMutableList()
        if (t.streamsParamIndex >= 0) values.add(t.streamsParamIndex, "streams")
        val call = "${t.qualifiedName}(${values.joinToString(", ")})"
        val firstParam = if (t.params.isEmpty()) "_" else "input"
        val lambdaParams = "$firstParam, ${if (t.streamsParamIndex >= 0) "streams" else "_"}"
        val handler = when (t.outputTypeDesc) {
            is TypeDesc.UnitT -> "{ $lambdaParams -> $call; SchemaValue.Unit_ }"
            is TypeDesc.Prim -> "{ $lambdaParams -> ${encode(t.outputTypeDesc, call)} }"
            else -> "{ $lambdaParams -> val golemResult = $call; ${encode(t.outputTypeDesc, "golemResult")} }"
        }
        val errors = if (t.errors.isEmpty()) {
            "emptyList()"
        } else {
            "listOf(${t.errors.joinToString(", ") {
                "cloud.golem.runtime.NativeToolErrorCase(${lit(it.name)}, ${lit(it.description)}, ${it.payloadWitType?.let { w -> lit(w) } ?: "null"}, ${it.usage}, ${it.exitCode})"
            }})"
        }
        return "cloud.golem.runtime.NativeToolRuntime.registerTool(cloud.golem.runtime.NativeToolDescriptor(" +
            "${lit(t.name)}, ${lit(t.description)}, $params, ${lit(t.outputWitType)}, " +
            "${t.stdin}, ${t.stdout}, ${t.stderr}, $errors, $handler))"
    }

    private fun methodDescriptor(className: String, m: MethodModel): String {
        val inputs = paramSchemaList(m.inputParams)
        val endpoints = if (m.httpEndpoints.isEmpty()) {
            "emptyList()"
        } else {
            "listOf(${m.httpEndpoints.joinToString(", ") {
                val vars = listOf("headerVars" to it.headerVars, "queryVars" to it.queryVars)
                    .filter { (_, pairs) -> pairs.isNotEmpty() }
                    .joinToString("") { (arg, pairs) -> ", $arg = listOf(${pairs.joinToString(", ") { p -> "${lit(p.first)} to ${lit(p.second)}" }})" } +
                    (it.durableStreams?.let { d -> ", durableStreams = ${durableStreams(d)}" } ?: "")
                "NativeHttpEndpoint(${lit(it.verb)}, ${lit(it.path)}, ${it.auth}, ${corsList(it.cors)}$vars)"
            }})"
        }
        val readOnly = m.readOnlyCache?.let { lit(it) } ?: "null"
        return "NativeMethodDescriptor(${lit(m.name)}, ${lit(m.description)}, ${lit(m.outputWitType)}, $inputs, $endpoints, ${lit(m.promptHint)}, $readOnly) ${handlerLambda(className, m)}"
    }

    private fun durableStreams(d: DurableStreamsModel): String {
        fun opt(v: Any?) = if (v == null) {
            "null"
        } else if (v is String) {
            lit(v)
        } else {
            v.toString()
        }
        val slots = d.slots.joinToString(", ") { "cloud.golem.runtime.NativeDurableSlot(${lit(it.source)}, ${lit(it.slot)}, ${opt(it.name)}, ${opt(it.contentType)})" }
        return "cloud.golem.runtime.NativeDurableStreams(listOf($slots), ${opt(d.allowExternalWrites)}, ${opt(d.allowStreamDelete)}, ${opt(d.allowInvocationDelete)}, ${opt(d.readers)}, ${opt(d.appends)})"
    }

    private fun handlerLambda(className: String, m: MethodModel): String {
        val args = m.inputParams.mapIndexed { i, p -> decode(p.typeDesc, "input[$i]") }.joinToString(", ")
        val secondParam = if (m.inputParams.isEmpty()) "_" else "input"
        val call = "(instance as $className).${m.name}($args)"
        return when (m.outputTypeDesc) {
            is TypeDesc.UnitT -> "{ instance, $secondParam -> $call; SchemaValue.Unit_ }"
            is TypeDesc.Prim -> "{ instance, $secondParam -> ${encode(m.outputTypeDesc, call)} }" // single-use, inline
            else -> // bind the result so composite encoders can reference its fields without re-invoking
                "{ instance, $secondParam -> val golemResult = $call; ${encode(m.outputTypeDesc, "golemResult")} }"
        }
    }

    /**
     * The `snapshotCodec = SnapshotCodec(...)` argument for the `NativeAgentDescriptor(...)` call,
     * or "" when the agent doesn't mix in `Snapshotted<S>`. Composes ConverterCodegen (Kotlin <->
     * SchemaValue) with SchemaValueBytes (SchemaValue <-> ByteArray). Fully-qualifies the runtime
     * references so no extra imports are needed in the generated file.
     */
    private fun snapshotArg(model: AgentModel): String {
        when (model.snapshotHooks) {
            "bytes" ->
                return ",\n" +
                    "            snapshotCodec = cloud.golem.runtime.SnapshotCodec(\n" +
                    "                save = { inst -> (inst as ${model.className}).saveSnapshot() },\n" +
                    "                load = { inst, bytes -> (inst as ${model.className}).loadSnapshot(bytes) },\n" +
                    "            )"
            "multipart" -> {
                // With Snapshotted<S> alongside, the derived state codec fills the frame's state slot and the
                // typed state is restored before the parts, so the parts hook sees the state it was saved with.
                val state = model.snapshotStateType
                val saveState = if (state == null) {
                    ""
                } else {
                    "cloud.golem.runtime.SchemaValueBytes.encode(${encode(state, "(inst as ${model.className}).state")})"
                }
                val loadState = if (state == null) {
                    ""
                } else {
                    "(inst as ${model.className}).state = " +
                        decode(state, "cloud.golem.runtime.SchemaValueBytes.decode(cloud.golem.MultipartSnapshot.decodeState(bytes))") +
                        "; "
                }
                return ",\n" +
                    "            snapshotCodec = cloud.golem.runtime.SnapshotCodec(\n" +
                    "                save = { inst -> (inst as ${model.className}).saveSnapshotParts().encode($saveState) },\n" +
                    "                load = { inst, bytes -> $loadState(inst as ${model.className}).loadSnapshotParts(cloud.golem.MultipartSnapshot.decode(bytes)) },\n" +
                    "            )"
            }
        }
        val td = model.snapshotStateType ?: return ""
        val enc = encode(td, "(inst as ${model.className}).state")
        val dec = decode(td, "cloud.golem.runtime.SchemaValueBytes.decode(bytes)")
        return ",\n" +
            "            snapshotCodec = cloud.golem.runtime.SnapshotCodec(\n" +
            "                save = { inst -> cloud.golem.runtime.SchemaValueBytes.encode($enc) },\n" +
            "                load = { inst, bytes -> (inst as ${model.className}).state = $dec },\n" +
            "            )"
    }

    private fun factoryLambda(model: AgentModel): String {
        val values = model.constructorParams.mapIndexed { i, p -> decode(p.typeDesc, "input[$i]") }.toMutableList()
        // The Config<T> parameter keeps its position among the constructor parameters but takes no input value.
        model.config?.let { values.add(model.configParamIndex, "cloud.golem.config.Config { ${it.buildExpression} }") }
        if (values.isEmpty()) return "{ _ -> ${model.className}() }"
        val param = if (model.constructorParams.isEmpty()) "_" else "input"
        return "{ $param -> ${model.className}(${values.joinToString(", ")}) }"
    }

    /** The router / live-file arguments of the descriptor (kind, bindings, response headers, OpenAPI provider), or "". */
    private fun httpArgs(model: AgentModel): String {
        fun mappings(list: List<FileMapping>) = list.joinToString(", ") {
            when (it) {
                is FileMapping.Exact -> "cloud.golem.runtime.NativeFileMapping(true, listOf(${it.publicPath.joinToString(", ") { s -> lit(s) }}), ${lit(it.filePath)})"
                is FileMapping.Subtree -> "cloud.golem.runtime.NativeFileMapping(false, listOf(${it.publicPrefix.joinToString(", ") { s -> lit(s) }}), ${lit(it.filesystemRoot)})"
            }
        }
        val parts = mutableListOf<String>()
        if (model.kind != "regular") parts += "kind = ${lit(model.kind)}"
        if (model.staticBindings.isNotEmpty()) parts += "staticBindings = listOf(${mappings(model.staticBindings)})"
        if (model.filesystemBindings.isNotEmpty()) parts += "filesystemBindings = listOf(${mappings(model.filesystemBindings)})"
        if (model.fileResponseHeaders.isNotEmpty()) {
            parts += "fileResponseHeaders = listOf(${model.fileResponseHeaders.joinToString(", ") { "${lit(it.first)} to ${lit(it.second)}" }})"
        }
        model.openApiProvider?.let { parts += "openApiProviderMethod = ${lit(it)}" }
        if (model.webhookSuffix.isNotEmpty()) parts += "webhookSuffix = ${lit(model.webhookSuffix)}"
        if (model.phantom) parts += "phantomAgent = true"
        model.phantomBinding?.let { (kind, name, optional) ->
            parts += "phantomIdBinding = cloud.golem.runtime.NativePhantomIdBinding(${lit(kind)}, ${lit(name)}, $optional)"
        }
        return parts.joinToString("") { ",\n            $it" }
    }

    /** The `config = listOf(NativeConfigDeclaration(..))` argument for the descriptor, or "" if the agent has no config. */
    private fun configArg(model: AgentModel): String {
        val config = model.config ?: return ""
        val items = config.declarations.joinToString(", ") {
            "cloud.golem.runtime.NativeConfigDeclaration(${lit(it.source)}, listOf(${it.path.joinToString(", ") { s -> lit(s) }}), ${lit(it.witType)})"
        }
        return ",\n            config = listOf($items)"
    }

    private fun decode(td: TypeDesc, sv: String): String = ConverterCodegen.decode(td, sv)
    private fun encode(td: TypeDesc, k: String): String = ConverterCodegen.encode(td, k)

    private fun paramSchemaList(params: List<ParamModel>): String = if (params.isEmpty()) {
        "emptyList()"
    } else {
        "listOf(${params.joinToString(", ") { "NativeParamSchema(${lit(it.name)}, ${lit(it.witType)})" }})"
    }

    private fun corsList(patterns: List<String>): String = if (patterns.isEmpty()) {
        "emptyList()"
    } else {
        "listOf(${patterns.joinToString(", ") { lit(it) }})"
    }

    /** Kotlin string literal with escaping. */
    private fun lit(s: String): String = kotlinStringLiteral(s)

    private fun aliasList(values: List<String>): String = if (values.isEmpty()) "emptyList()" else "listOf(${values.joinToString(", ") { lit(it) }})"

    private fun write(packageName: String, fileName: String, code: String) {
        codeGenerator.createNewFile(
            dependencies = Dependencies.ALL_FILES,
            packageName = packageName,
            fileName = fileName,
            extensionName = "kt",
        ).bufferedWriter().use { it.write(code) }
    }
