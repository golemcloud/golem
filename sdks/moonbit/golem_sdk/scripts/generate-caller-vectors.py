#!/usr/bin/env python3
"""Writes caller/vectors_wbtest.mbt from the shared principal-reference text vectors.

MoonBit tests cannot read the repository's JSON file, so the vectors are embedded.
Run from the golem_sdk module root after the vectors change:

  python3 scripts/generate-caller-vectors.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[1]
repo = root.parents[2]
vectors = json.loads((repo / "test-data/caller-identity/text-form-v1.json").read_text(encoding="utf-8"))


def literal(text: str) -> str:
    out = ['"']
    for ch in text:
        code = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif code < 0x20 or code == 0x7F or 0x80 <= code <= 0x9F or code in (0x2028, 0x2029):
            out.append("\\u{%x}" % code)
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


lines = [
    "// Generated by scripts/generate-caller-vectors.py from",
    "// test-data/caller-identity/text-form-v1.json. Do not edit.",
    "",
    "///|",
    "test \"principal reference text form matches the shared vectors\" {",
]
for case in vectors["roundTrip"]:
    lines.append(
        f"  check_round_trip({literal(case['name'])}, {literal(case['issuer'])}, {literal(case['subject'])}, {literal(case['text'])})"
    )
lines.append("}")
lines += ["", "///|", "test \"principal reference parser refuses every non-canonical spelling\" {"]
for case in vectors["reject"]:
    lines.append(f"  check_rejected({literal(case['name'])}, {literal(case['text'])})")
lines.append("}")
(root / "caller" / "vectors_wbtest.mbt").write_text("\n".join(lines) + "\n", encoding="utf-8")
