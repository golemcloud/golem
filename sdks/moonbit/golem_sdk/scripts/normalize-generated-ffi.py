#!/usr/bin/env python3
"""Make nondeterministically ordered generated MoonBit FFI declarations stable."""

import argparse
import re
from pathlib import Path


GENERATED_HEADER = "// Generated by `wit-bindgen`"
BLOCK_DELIMITER = "\n///|\n"
WRAPPER_DELIMITER = "\n\n#doc(hidden)\n"
ROOT_GEN_PACKAGES = {"gen", "gen-tool-middleware", "gen-agent-tool-middleware"}
HELPER_DECL = re.compile(
    r'^extern "wasm" fn (mbt_ffi_[A-Za-z0-9_]+)', re.MULTILINE
)
ANY_HELPER_DECL = re.compile(
    r'^[ \t]*extern "wasm" fn (mbt_ffi_[A-Za-z0-9_]+)', re.MULTILINE
)
WRAPPER_DECL = re.compile(r"^pub fn (wasmExport[A-Za-z0-9_]+)", re.MULTILINE)
ANY_WRAPPER_DECL = re.compile(
    r"^[ \t]*pub fn (wasmExport[A-Za-z0-9_]+)", re.MULTILINE
)


def helper_name(block: str, path: Path) -> str | None:
    candidate = block.split(WRAPPER_DELIMITER, 1)[0]
    matches = list(HELPER_DECL.finditer(candidate))
    if not matches:
        return None
    if len(matches) != 1:
        raise SystemExit(f"expected one generated FFI helper per block in {path}")
    match = matches[0]
    prefix = candidate[: match.start()].strip()
    if prefix and re.fullmatch(r"#owned\([A-Za-z0-9_]+\)", prefix) is None:
        raise SystemExit(f"unexpected generated FFI helper prefix in {path}")
    return match.group(1)


def normalize_wrappers(trailer: str, path: Path) -> tuple[str, list[str]]:
    if not trailer.startswith("#doc(hidden)\n"):
        raise SystemExit(f"unexpected generated wrapper trailer in {path}")
    blocks = trailer.removeprefix("#doc(hidden)\n").split(WRAPPER_DELIMITER)
    normalized: list[tuple[str, str]] = []
    for block in blocks:
        block = block.strip()
        matches = list(WRAPPER_DECL.finditer(block))
        if len(matches) != 1 or matches[0].start() != 0:
            raise SystemExit(
                f"expected one generated export wrapper per block in {path}"
            )
        match = matches[0]
        normalized.append((match.group(1), block))
    names = [name for name, _ in normalized]
    if len(names) != len(set(names)):
        raise SystemExit(f"duplicate generated wrapper in {path}")
    result = "#doc(hidden)\n" + WRAPPER_DELIMITER.join(
        block for _, block in sorted(normalized)
    )
    return result, names


def normalize(text: str, path: Path) -> str:
    if not text.startswith(GENERATED_HEADER):
        raise SystemExit(f"refusing to normalize non-generated file: {path}")
    parts = text.split(BLOCK_DELIMITER)
    helpers: list[tuple[str, str]] = []
    helper_indices: list[int] = []
    wrapper_index: int | None = None
    wrapper_trailer: str | None = None
    wrapper_names: list[str] = []
    wrappers: list[tuple[str, str]] = []
    wrapper_indices: list[int] = []
    for index, part in enumerate(parts):
        stripped = part.strip()
        if stripped.startswith("#doc(hidden)\n"):
            matches = list(WRAPPER_DECL.finditer(stripped))
            if len(matches) == 1:
                wrappers.append((matches[0].group(1), stripped))
                wrapper_indices.append(index)
        name = helper_name(part, path)
        if name is None:
            continue
        helper = part
        if WRAPPER_DELIMITER in helper:
            if wrapper_index is not None:
                raise SystemExit(f"multiple generated wrapper trailers in {path}")
            helper, wrapper_trailer = helper.split(WRAPPER_DELIMITER, 1)
            wrapper_index = index
            wrapper_trailer = "#doc(hidden)\n" + wrapper_trailer
        helpers.append((name, helper.strip()))
        helper_indices.append(index)
    names = [name for name, _ in helpers]
    if len(names) != len(set(names)):
        raise SystemExit(f"duplicate generated FFI helper in {path}")
    for index, (_, helper) in zip(helper_indices, sorted(helpers), strict=True):
        parts[index] = helper
    standalone_wrapper_names = [name for name, _ in wrappers]
    if len(standalone_wrapper_names) != len(set(standalone_wrapper_names)):
        raise SystemExit(f"duplicate generated wrapper in {path}")
    for index, (_, wrapper) in zip(wrapper_indices, sorted(wrappers), strict=True):
        parts[index] = wrapper
    wrapper_names.extend(standalone_wrapper_names)
    if wrapper_index is not None and wrapper_trailer is not None:
        normalized_wrappers, wrapper_names = normalize_wrappers(wrapper_trailer, path)
        parts[wrapper_index] += "\n\n" + normalized_wrappers
    all_helper_names = ANY_HELPER_DECL.findall(text)
    if sorted(all_helper_names) != sorted(names):
        raise SystemExit(f"unrecognized generated FFI helper declaration in {path}")
    if path.parent.name in ROOT_GEN_PACKAGES:
        all_wrapper_names = ANY_WRAPPER_DECL.findall(text)
        if sorted(all_wrapper_names) != sorted(wrapper_names):
            raise SystemExit(f"unrecognized generated export wrapper declaration in {path}")
    return BLOCK_DELIMITER.join(parts).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("roots", nargs="+", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    paths = sorted(
        path
        for root in args.roots
        for path in ([root] if root.is_file() else root.rglob("ffi.mbt"))
    )
    if not paths:
        raise SystemExit("no generated ffi.mbt files found")
    changed: list[Path] = []
    for path in paths:
        text = path.read_text()
        normalized = normalize(text, path)
        if normalize(normalized, path) != normalized:
            raise SystemExit(f"normalization is not idempotent: {path}")
        if normalized != text:
            changed.append(path)
            if not args.check:
                path.write_text(normalized)
    if args.check and changed:
        files = "\n".join(str(path) for path in changed)
        raise SystemExit(f"generated FFI files are not normalized:\n{files}")


if __name__ == "__main__":
    main()
