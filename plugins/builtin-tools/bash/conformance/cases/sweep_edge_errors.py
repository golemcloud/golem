CASES = []
for label, command in READERS:
    for kind, template in KINDS:
        CASES.append((f"edge errors: {label} {kind}", util(template.replace("{c}", command))))

# sed and jq: the same error kinds, compared by status only.
for label, command in [("sed", "sed p"), ("sed -i", "sed -i p"), ("jq", "jq .")]:
    for kind, template in KINDS:
        CASES.append((f"edge errors: {label} {kind}", status_only(template.replace("{c}", command))))

