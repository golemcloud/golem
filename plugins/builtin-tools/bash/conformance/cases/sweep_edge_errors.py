"""Edge inputs: every reachable error path. Missing files, directories where files are expected,
empty and not-a-directory paths, bad options and option arguments, missing and extra operands,
builtin misuse, expansion and redirection errors, and how errors propagate through pipelines,
substitutions and errexit.

GNU quotes some names with curly quotes under the oracle's UTF-8 locale where this shell (like GNU
without a locale) uses ASCII quotes; special_paths.py documents that as deliberate. Utility cases
therefore merge stderr into stdout and fold the curly quotes to ASCII, so everything else about
the diagnostic and the status is still compared. sed's and jq's diagnostics are documented to differ
in wording (sed.py, jq.py), so their cases compare the status only.

Generated from fixed tables with plain loops, so every Python 3 produces the same scripts.
"""

TIER = "sweep"
ERROR_PATHS = True

QUOTES = " 2>&1 | sed \"s/[‘’]/'/g\""


def util(script):
    """A utility error case: status and diagnostic on stdout, curly quotes folded."""
    return "{ " + script + "; echo \"status=$?\"; }" + QUOTES


def status_only(script):
    return script + " 2>/dev/null; echo \"status=$?\""


