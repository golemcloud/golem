fn uuid_to_core2(value: uuid::Uuid) -> golem_schema::schema::wit::wire::Uuid {
    let (high_bits, low_bits) = value.as_u64_pair();
    golem_schema::schema::wit::wire::Uuid {
        high_bits,
        low_bits,
    }
}

fn uuid_from_core2(value: golem_schema::schema::wit::wire::Uuid) -> uuid::Uuid {
    uuid::Uuid::from_u64_pair(value.high_bits, value.low_bits)
}

impl From<ComponentId> for golem_schema::schema::wit::wire::ComponentId {
    fn from(value: ComponentId) -> Self {
        Self {
            uuid: uuid_to_core2(value.0),
        }
    }
}

