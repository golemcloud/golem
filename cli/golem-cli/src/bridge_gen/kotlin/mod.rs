    /// `path` and `union` carry their full spec on the lowered path (`AgentTypeModel.kt`'s
    /// schema-graph builder), via the hex-encoded grammar `sdk_wit.rs` renders, so a config
    /// override of either succeeds.
    #[test]
    fn a_config_override_of_a_path_or_a_union_carries_its_spec() {
        use golem_common::model::agent::AgentConfigSource;
        use golem_common::schema::agent::AgentConfigDeclarationSchema;
        use golem_common::schema::schema_type::{
            DiscriminatorRule, PathDirection, PathKind, PathSpec, UnionBranch, UnionSpec,
        };
        for (value_type, expected) in [
            (
                SchemaType::path(PathSpec {
                    direction: PathDirection::Input,
                    kind: PathKind::File,
                    allowed_mime_types: Some(vec!["image/png".to_string()]),
                    allowed_extensions: None,
                }),
                // direction=input, kind=file, mime=["image/png"] hex-encoded, extensions=none.
                "path<input,file,<696d6167652f706e67>,_>",
            ),
            (
                SchemaType::union(UnionSpec {
                    branches: vec![UnionBranch {
                        tag: "a".to_string(),
                        body: SchemaType::s32(),
                        discriminator: DiscriminatorRule::FieldAbsent {
                            field_name: "kind".to_string(),
                        },
                        metadata: Default::default(),
                    }],
                }),
                // tag="a" hex-encoded, body=s32, field-absent("kind") hex-encoded.
                "union<<61,s32,field-absent<6b696e64>>>",
            ),
        ] {
            let mut agent = rich_agent();
            agent.config = vec![AgentConfigDeclarationSchema {
                source: AgentConfigSource::Local,
                path: vec!["setting".to_string()],
                value_type,
            }];
            let code = guest_source(agent);
            assert!(code.contains(expected), "missing {expected}:\n{code}");
        }
    }

