//! Kotlin bridge SDK generator.
//!
//! Guest mode emits a Kotlin/Wasm library that calls other agents through the
//! Golem Kotlin SDK's wasm-RPC layer. External mode emits a self-contained
//! Kotlin/JVM project that embeds a REST runtime and depends only on the JDK.
//! Type definitions and `SchemaValue` codecs are generated by the same code in
//! both modes; the two modes differ only in the runtime package that supplies
//! `SchemaValue` and the types the codecs surface (`Uuid`, `Datetime`,
//! `Either`, the unstructured text and binary wrappers). Both runtimes expose
//! `SchemaValue` with identical case names and shapes.
//!
//! Every reference to a generated or runtime type is fully qualified, so a
//! user-chosen member or parameter name can never shadow it. Package segments
//! that could be shadowed by a parameter (`kotlin`, `cloud`, `golem`, `java`)
//! are reserved as parameter names.

