    /// `when` used as an expression needs at least one branch, so an empty sum
    /// type would generate a client that does not compile.
    #[test]
    fn an_empty_sum_type_is_rejected() {
        use golem_common::schema::schema_type::{UnionBranch, UnionSpec};
        let empty_variant = SchemaType::variant(vec![]);
        let empty_enum = SchemaType::r#enum(Vec::<String>::new());
        let empty_union = SchemaType::union(UnionSpec {
            branches: Vec::<UnionBranch>::new(),
        });
        for (label, body) in [
            ("variant", empty_variant),
            ("enum", empty_enum),
            ("union", empty_union),
        ] {
            let mut agent = rich_agent();
            agent.schema.defs.push(def("empty.Sum", body));
            agent.constructor.input_schema =
                InputSchema::parameters(vec![NamedField::user_supplied(
                    "v",
                    reference("empty.Sum"),
                )]);
            let error = KotlinBridgeGenerator::new_core(
                agent,
                Utf8Path::new("unused"),
                KotlinBridgeMode::GuestWasmRpc,
                std::iter::empty::<String>(),
            )
            .and_then(|g| g.generate_guest_client_source())
            .expect_err(&format!("an empty {label} must fail generation"))
            .to_string();
            assert!(
                error.contains("`when` used as an expression needs at least one branch")
                    && error.contains(label),
                "the error must name the empty sum: {error}"
            );
        }
    }

