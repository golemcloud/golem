/// The largest tuple arity whose generated `TupleN` name is reserved against
/// schema-derived type names. A wider tuple would emit a `TupleN` that
/// `TypeNaming` could also hand to a schema type called `tuple-N`, so
/// [`tuple_type`](KotlinBridgeGenerator::tuple_type) refuses it instead.
const TUPLE_ARITY_RESERVED_MAX: usize = 32;

/// Root package of the generated client. A per-agent segment is appended, which
/// separates clients whose agent-type names differ by more than their separators
/// or case. Two names that snake-case alike (`foo-bar` and `fooBar`) still land
/// in one package with the same object names; each client is its own Gradle
/// project, so that only matters if both are put on one classpath. The generator
/// renders one agent type at a time and cannot detect the clash from here.
const CLIENT_PKG_BASE: &str = "golem.bridge.client";

const STREAM_SESSION: &str = "golem.bridge.runtime.StreamSession";
const AGENT_STREAM: &str = "golem.bridge.runtime.AgentStream";

/// Generated object holding the per-named-type `encode<Name>` / `decode<Name>`
/// functions.
const CODECS_OBJECT: &str = "Codecs";

/// Generated object with the typed `SchemaValue` accessors.
const CODEC_HELPER_OBJECT: &str = "BridgeCodec";

/// The guest-mode exception thrown by generated codecs on a wire-shape
/// mismatch (the external runtime has its own `BridgeException`).
const GUEST_CODEC_EXCEPTION: &str = "BridgeCodecException";

static CODEC_HELPER_TEMPLATE: &str = include_str!("codec_helper.kt.in");

/// Names a parameter must not take: generated code names these packages by
/// their fully qualified path, and a parameter of the same name would shadow
/// the first segment.
pub(crate) const PACKAGE_ROOT_NAMES: &[&str] = &["kotlin", "cloud", "golem", "java"];

/// Member names a generated record/flags property or a variant/enum case must
/// not use: `class` would clash with `getClass`, and the enum members below
/// are inherited by every `enum class`.
const RESERVED_PROPERTY_NAMES: &[&str] = &["class"];
const RESERVED_ENUM_ENTRY_NAMES: &[&str] = &[
    "name",
    "ordinal",
    "values",
    "valueOf",
    "entries",
    "compareTo",
    "hashCode",
    "toString",
    "equals",
    "describeConstable",
    "getDeclaringClass",
];

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum KotlinBridgeMode {
    ExternalRest,
    GuestWasmRpc,
}

impl KotlinBridgeMode {
    pub(crate) fn bridge_mode(self) -> BridgeMode {
        match self {
            KotlinBridgeMode::ExternalRest => BridgeMode::External,
            KotlinBridgeMode::GuestWasmRpc => BridgeMode::Guest,
        }
    }
}

/// What differs between the two runtimes, as fully qualified Kotlin names.
#[derive(Clone, Copy, Debug)]
pub(crate) struct KotlinRuntimeConfig {
    pub schema_value: &'static str,
    pub exception: &'static str,
    pub uuid: &'static str,
    pub datetime: &'static str,
    pub either: &'static str,
    pub unstructured_text: &'static str,
    pub unstructured_binary: &'static str,
    pub quantity: &'static str,
}

impl KotlinRuntimeConfig {
    pub(crate) fn new(mode: KotlinBridgeMode) -> Self {
        match mode {
            KotlinBridgeMode::GuestWasmRpc => Self {
                schema_value: "cloud.golem.runtime.SchemaValue",
                exception: GUEST_CODEC_EXCEPTION,
                uuid: "cloud.golem.runtime.Uuid",
                datetime: "cloud.golem.Datetime",
                either: "cloud.golem.runtime.Either",
                unstructured_text: "cloud.golem.schema.UnstructuredText",
                unstructured_binary: "cloud.golem.schema.UnstructuredBinary",
                quantity: "cloud.golem.schema.Quantity",
            },
            KotlinBridgeMode::ExternalRest => Self {
                schema_value: "golem.bridge.runtime.SchemaValue",
                exception: "golem.bridge.runtime.BridgeException",
                uuid: "golem.bridge.runtime.Uuid",
                datetime: "golem.bridge.runtime.Datetime",
                either: "golem.bridge.runtime.Either",
                unstructured_text: "golem.bridge.runtime.UnstructuredText",
                unstructured_binary: "golem.bridge.runtime.UnstructuredBinary",
                quantity: "golem.bridge.runtime.Quantity",
            },
        }
    }

    /// Simple type names of the runtime, which a generated type must not take.
    fn reserved_type_names(self) -> &'static [&'static str] {
        &[
            "SchemaValue",
            "Either",
            "Uuid",
            "Datetime",
            "UnstructuredText",
            "UnstructuredBinary",
            "BridgeException",
            "BridgeCodecException",
        ]
    }
}

/// Core of the Kotlin generators: names, type definitions and codecs for one
/// agent type. The agent-specific client surface is built on top of it.
pub struct KotlinBridgeGenerator {
    pub(crate) target_path: Utf8PathBuf,
    pub(crate) agent_type: AgentTypeSchema,
    pub(crate) mode: KotlinBridgeMode,
    pub(crate) runtime: KotlinRuntimeConfig,
    pub(crate) same_language: bool,
    /// Appended to the per-agent package segment, so a tool client and an agent client of the same name get different packages.
    pub(crate) package_suffix: &'static str,
    pub(crate) type_naming: TypeNaming<KotlinTypeName>,
    /// Arities (other than 2 and 3) of tuples that occur in the schema; each
    /// gets a generated `Tuple<N>` class.
    tuple_arities: RefCell<BTreeSet<usize>>,
}

impl KotlinBridgeGenerator {
    pub(crate) fn new_core(
        agent_type: AgentTypeSchema,
        target_path: &Utf8Path,
        mode: KotlinBridgeMode,
        extra_reserved_names: impl IntoIterator<Item = String>,
    ) -> anyhow::Result<Self> {
        validate_host_managed_agent_bridge_policy(&agent_type, mode.bridge_mode())?;
        let same_language = agent_type.source_language.eq_ignore_ascii_case("kotlin");
        let runtime = KotlinRuntimeConfig::new(mode);
        let reserved = runtime
            .reserved_type_names()
            .iter()
            .map(|name| KotlinTypeName::Derived((*name).to_string()))
            .chain(
                [CODECS_OBJECT, CODEC_HELPER_OBJECT, "RemoteFuture"]
                    .into_iter()
                    .map(|name| KotlinTypeName::Derived(name.to_string()))
                    .chain(
                        [
                            client_object_name(&agent_type),
                            remote_class_name(&agent_type),
                        ]
                        .into_iter()
                        .map(KotlinTypeName::Derived),
                    ),
            )
            .chain(
                std::iter::once(1)
                    .chain(4..=TUPLE_ARITY_RESERVED_MAX)
                    .map(|n| KotlinTypeName::Derived(format!("Tuple{n}"))),
            )
            .chain(
                extra_reserved_names
                    .into_iter()
                    .map(KotlinTypeName::Derived),
            );
        let type_naming =
            TypeNaming::new_with_reserved_names(&agent_type, same_language, reserved)?;
        Ok(Self {
            target_path: target_path.to_path_buf(),
            agent_type,
            mode,
            runtime,
            same_language,
            package_suffix: "",
            type_naming,
            tuple_arities: RefCell::new(BTreeSet::new()),
        })
    }

    /// The per-agent client package segment, derived from the agent type name
    /// (`CounterAgent` -> `counter_agent`). Always a plain lowercase package
    /// identifier.
    pub(crate) fn client_package_segment(&self) -> String {
        let mut seg: String = self
            .agent_type
            .type_name
            .as_str()
            .to_snake_case()
            .chars()
            .map(|c| {
                if c.is_ascii_alphanumeric() || c == '_' {
                    c.to_ascii_lowercase()
                } else {
                    '_'
                }
            })
            .collect();
        if seg.is_empty() {
            seg = "agent".to_string();
        }
        if !seg.starts_with(|c: char| c.is_ascii_alphabetic()) {
            seg = format!("agent_{seg}");
        }
        if is_kotlin_keyword(&seg) {
            seg = format!("{seg}_");
        }
        seg
    }

    /// The dotted client package, e.g. `golem.bridge.client.counter_agent`.
    pub(crate) fn client_package(&self) -> String {
        format!(
            "{CLIENT_PKG_BASE}.{}{}",
            self.client_package_segment(),
            self.package_suffix
        )
    }

    fn qualified(&self, name: &str) -> String {
        format!("{}.{name}", self.client_package())
    }

    pub(crate) fn sv(&self) -> &'static str {
        self.runtime.schema_value
    }

    fn exception(&self) -> &'static str {
        self.runtime.exception
    }

    /// The source of the file-private `SchemaValue` alias, the guest-mode
    /// exception (external mode uses the runtime's), and the `BridgeCodec`
    /// accessor object.
    pub(crate) fn codec_helper_source(&self) -> String {
        let exception_decl = match self.mode {
            KotlinBridgeMode::GuestWasmRpc => format!(
                "class {GUEST_CODEC_EXCEPTION}(message: kotlin.String) : kotlin.RuntimeException(message)"
            ),
            KotlinBridgeMode::ExternalRest => String::new(),
        };
        CODEC_HELPER_TEMPLATE
            .replace("{{EXCEPTION_DECL}}", &exception_decl)
            .replace("{{EXCEPTION}}", self.exception())
            .replace("{{SV}}", self.runtime.schema_value)
            .replace("{{UUID}}", self.runtime.uuid)
            .replace("{{DATETIME}}", self.runtime.datetime)
            .replace("{{UNSTRUCTURED_TEXT}}", self.runtime.unstructured_text)
            .replace("{{UNSTRUCTURED_BINARY}}", self.runtime.unstructured_binary)
            .replace("{{QUANTITY}}", self.runtime.quantity)
    }

    // --- Identifiers --------------------------------------------------------

    /// Property identifiers for the given schema names, unique among themselves
    /// and clear of the reserved property names.
    pub(crate) fn term_member_idents<'a>(
        &self,
        names: impl Iterator<Item = &'a str>,
    ) -> Vec<String> {
        let idents = names
            .map(|n| to_kotlin_term_ident(n, self.same_language))
            .collect();
        unique_idents_with_reserved(idents, RESERVED_PROPERTY_NAMES)
    }

    /// Case identifiers for variants, unions: UpperCamelCase, unique.
    pub(crate) fn type_member_idents<'a>(
        &self,
        names: impl Iterator<Item = &'a str>,
    ) -> Vec<String> {
        unique_idents(names.map(|n| self.case_ident(n)).collect())
    }

    /// Entry identifiers for enums: like [`Self::type_member_idents`] but clear
    /// of the members every Kotlin enum inherits.
    pub(crate) fn enum_entry_idents<'a>(
        &self,
        names: impl Iterator<Item = &'a str>,
    ) -> Vec<String> {
        unique_idents_with_reserved(
            names.map(|n| self.case_ident(n)).collect(),
            RESERVED_ENUM_ENTRY_NAMES,
        )
    }

    fn case_ident(&self, name: &str) -> String {
        if self.same_language {
            escape_kotlin_ident(name)
        } else {
            escape_kotlin_ident(&name.to_upper_camel_case())
        }
    }

    // --- Type definitions ---------------------------------------------------

    /// Emits the definition of every generated named composite type.
    pub(crate) fn write_type_definitions(&self, writer: &mut KotlinWriter) -> anyhow::Result<()> {
        let types: Vec<(SchemaType, KotlinTypeName)> = self
            .type_naming
            .types()
            .map(|(t, n)| (t.clone(), n.clone()))
            .collect();
        for (typ, name) in &types {
            let KotlinTypeName::Derived(name_str) = name else {
                continue;
            };
            let resolved = self.resolve_ref(typ);
            if !is_named_composite(resolved) {
                continue;
            }
            self.write_type_definition(writer, name_str, resolved)?;
            writer.blank();
        }
        Ok(())
    }

    fn write_type_definition(
        &self,
        writer: &mut KotlinWriter,
        name: &str,
        resolved: &SchemaType,
    ) -> anyhow::Result<()> {
        let self_type = self.qualified(name);
        match resolved {
            SchemaType::Record { fields, .. } => {
                if fields.is_empty() {
                    writer.line(format!("data object {name}"));
                } else {
                    let field_names =
                        self.term_member_idents(fields.iter().map(|f| f.name.as_str()));
                    writer.line(format!("data class {name}("));
                    writer.indent();
                    for (idx, field) in fields.iter().enumerate() {
                        let field_type = self.type_reference(&field.body)?;
                        let comma = if idx + 1 < fields.len() { "," } else { "" };
                        writer.line(format!("val {}: {field_type}{comma}", field_names[idx]));
                    }
                    writer.dedent();
                    writer.line(")");
                }
            }
            SchemaType::Variant { cases, .. } => {
                let case_names = self.type_member_idents(cases.iter().map(|c| c.name.as_str()));
                writer.line(format!("sealed class {name} {{"));
                writer.indent();
                for (idx, case) in cases.iter().enumerate() {
                    let case_name = &case_names[idx];
                    match &case.payload {
                        Some(payload) => {
                            let payload_type = self.type_reference(payload)?;
                            writer.line(format!(
                                "data class {case_name}(val value: {payload_type}) : {self_type}()"
                            ));
                        }
                        None => {
                            writer.line(format!("data object {case_name} : {self_type}()"));
                        }
                    }
                }
                writer.dedent();
                writer.line("}");
            }
            SchemaType::Enum { cases, .. } => {
                let case_names = self.enum_entry_idents(cases.iter().map(|c| c.as_str()));
                writer.line(format!("enum class {name} {{"));
                writer.indent();
                for (idx, case_name) in case_names.iter().enumerate() {
                    let sep = if idx + 1 < case_names.len() { "," } else { "" };
                    writer.line(format!("{case_name}{sep}"));
                }
                writer.dedent();
                writer.line("}");
            }
            SchemaType::Flags { flags, .. } => {
                if flags.is_empty() {
                    writer.line(format!("data object {name}"));
                } else {
                    let flag_names = self.term_member_idents(flags.iter().map(|f| f.as_str()));
                    writer.line(format!("data class {name}("));
                    writer.indent();
                    for (idx, flag_name) in flag_names.iter().enumerate() {
                        let comma = if idx + 1 < flag_names.len() { "," } else { "" };
                        writer.line(format!("val {flag_name}: kotlin.Boolean{comma}"));
                    }
                    writer.dedent();
                    writer.line(")");
                }
            }
            SchemaType::Union { spec, .. } => {
                let branch_names =
                    self.type_member_idents(spec.branches.iter().map(|b| b.tag.as_str()));
                writer.line(format!("sealed class {name} {{"));
                writer.indent();
                for (idx, branch) in spec.branches.iter().enumerate() {
                    let payload_type = self.type_reference(&branch.body)?;
                    writer.line(format!(
                        "data class {}(val value: {payload_type}) : {self_type}()",
                        branch_names[idx]
                    ));
                }
                writer.dedent();
                writer.line("}");
            }
            other => {
                bail!("Unexpected non-composite type reached write_type_definition: {other:?}")
            }
        }
        Ok(())
    }

    /// Emits the generated `Tuple<N>` classes for every tuple arity that
    /// occurs in the schema and has no Kotlin standard class (1 and 4+).
    /// Call after all type references have been rendered.
    pub(crate) fn write_tuple_types(&self, writer: &mut KotlinWriter) {
        for arity in self.tuple_arities.borrow().iter() {
            let params = (1..=*arity)
                .map(|i| format!("T{i}"))
                .collect::<Vec<_>>()
                .join(", ");
            let fields = (1..=*arity)
                .map(|i| format!("val v{i}: T{i}"))
                .collect::<Vec<_>>()
                .join(", ");
            writer.line(format!("data class Tuple{arity}<{params}>({fields})"));
            writer.blank();
        }
    }

    // --- Codecs -------------------------------------------------------------

    /// Emits `object Codecs { … }` with an `encode<Name>` / `decode<Name>`
    /// pair for every generated named composite type. Non-composite aliases and
    /// remapped types are encoded inline at their use sites.
    pub(crate) fn write_codecs(&self, writer: &mut KotlinWriter) -> anyhow::Result<()> {
        let types: Vec<(SchemaType, KotlinTypeName)> = self
            .type_naming
            .types()
            .map(|(t, n)| (t.clone(), n.clone()))
            .collect();
        writer.line(format!("object {CODECS_OBJECT} {{"));
        writer.indent();
        for (typ, name) in &types {
            let KotlinTypeName::Derived(name_str) = name else {
                continue;
            };
            let resolved = self.resolve_ref(typ);
            if !is_named_composite(resolved) {
                continue;
            }
            self.write_encode_fn(writer, name_str, resolved)?;
            writer.blank();
            self.write_decode_fn(writer, name_str, resolved)?;
            writer.blank();
        }
        writer.dedent();
        writer.line("}");
        writer.blank();
        Ok(())
    }

    fn write_encode_fn(
        &self,
        writer: &mut KotlinWriter,
        name: &str,
        resolved: &SchemaType,
    ) -> anyhow::Result<()> {
        let sv = self.sv();
        let self_type = self.qualified(name);
        writer.line(format!("fun encode{name}(value: {self_type}): {sv} {{"));
        writer.indent();
        match resolved {
            SchemaType::Record { fields, .. } => {
                let field_names = self.term_member_idents(fields.iter().map(|f| f.name.as_str()));
                let mut elems = Vec::new();
                for (idx, field) in fields.iter().enumerate() {
                    let enc =
                        self.encode_expr(&format!("value.{}", field_names[idx]), &field.body, 0)?;
                    writer.line(format!("val f{idx} = {enc}"));
                    elems.push(format!("f{idx}"));
                }
                writer.line(format!(
                    "return {sv}.Record(kotlin.collections.listOf({}))",
                    elems.join(", ")
                ));
            }
            SchemaType::Variant { cases, .. } => {
                if cases.is_empty() {
                    bail!(
                        "A variant with no cases has no Kotlin representation: `when` used as an expression needs at least one branch"
                    );
                }
                let case_names = self.type_member_idents(cases.iter().map(|c| c.name.as_str()));
                writer.line("return when (value) {");
                writer.indent();
                for (idx, case) in cases.iter().enumerate() {
                    let case_name = &case_names[idx];
                    match &case.payload {
                        Some(payload) => {
                            let enc = self.encode_expr("value.value", payload, 0)?;
                            writer.line(format!("is {self_type}.{case_name} -> {{"));
                            writer.indent();
                            writer.line(format!("val p = {enc}"));
                            writer.line(format!("{sv}.VariantVal({idx}, p)"));
                            writer.dedent();
                            writer.line("}");
                        }
                        None => {
                            writer.line(format!(
                                "{self_type}.{case_name} -> {sv}.VariantVal({idx}, null)"
                            ));
                        }
                    }
                }
                writer.dedent();
                writer.line("}");
            }
            SchemaType::Enum { cases, .. } => {
                if cases.is_empty() {
                    bail!(
                        "An enum with no cases has no Kotlin representation: `when` used as an expression needs at least one branch"
                    );
                }
                let case_names = self.enum_entry_idents(cases.iter().map(|c| c.as_str()));
                writer.line("return when (value) {");
                writer.indent();
                for (idx, case_name) in case_names.iter().enumerate() {
                    writer.line(format!("{self_type}.{case_name} -> {sv}.EnumVal({idx})"));
                }
                writer.dedent();
                writer.line("}");
            }
            SchemaType::Flags { flags, .. } => {
                let flag_names = self.term_member_idents(flags.iter().map(|f| f.as_str()));
                if flag_names.is_empty() {
                    writer.line(format!(
                        "return {sv}.FlagsVal(kotlin.collections.emptyList())"
                    ));
                } else {
                    let bits = flag_names
                        .iter()
                        .map(|f| format!("value.{f}"))
                        .collect::<Vec<_>>()
                        .join(", ");
                    writer.line(format!(
                        "return {sv}.FlagsVal(kotlin.collections.listOf({bits}))"
                    ));
                }
            }
            SchemaType::Union { spec, .. } => {
                if spec.branches.is_empty() {
                    bail!(
                        "A union with no branches has no Kotlin representation: `when` used as an expression needs at least one branch"
                    );
                }
                let branch_names =
                    self.type_member_idents(spec.branches.iter().map(|b| b.tag.as_str()));
                writer.line("return when (value) {");
                writer.indent();
                for (idx, branch) in spec.branches.iter().enumerate() {
                    let branch_name = &branch_names[idx];
                    let enc = self.encode_expr("value.value", &branch.body, 0)?;
                    writer.line(format!("is {self_type}.{branch_name} -> {{"));
                    writer.indent();
                    writer.line(format!("val b = {enc}"));
                    writer.line(format!(
                        "{sv}.UnionVal({}, b)",
                        kotlin_string_literal(branch.tag.as_str())
                    ));
                    writer.dedent();
                    writer.line("}");
                }
                writer.dedent();
                writer.line("}");
            }
            other => bail!("Unexpected non-composite type reached write_encode_fn: {other:?}"),
        }
        writer.dedent();
        writer.line("}");
        Ok(())
    }

    fn write_decode_fn(
        &self,
        writer: &mut KotlinWriter,
        name: &str,
        resolved: &SchemaType,
    ) -> anyhow::Result<()> {
        let sv = self.sv();
        let exc = self.exception();
        let helper = CODEC_HELPER_OBJECT;
        let self_type = self.qualified(name);
        writer.line(format!("fun decode{name}(value: {sv}): {self_type} {{"));
        writer.indent();
        match resolved {
            SchemaType::Record { fields, .. } => {
                let n = fields.len();
                writer.line(format!("val fields = {helper}.recordFields(value)"));
                writer.line(format!(
                    "if (fields.size != {n}) throw {exc}(\"Expected record {name} with {n} fields, got ${{fields.size}}\")"
                ));
                if n == 0 {
                    writer.line(format!("return {self_type}"));
                } else {
                    let mut args = Vec::new();
                    for (idx, field) in fields.iter().enumerate() {
                        let dec = self.decode_expr(&format!("fields[{idx}]"), &field.body, 0)?;
                        writer.line(format!("val f{idx} = {dec}"));
                        args.push(format!("f{idx}"));
                    }
                    writer.line(format!("return {self_type}({})", args.join(", ")));
                }
            }
            SchemaType::Variant { cases, .. } => {
                let case_names = self.type_member_idents(cases.iter().map(|c| c.name.as_str()));
                writer.line(format!(
                    "val (caseIndex, payload) = {helper}.variantCase(value)"
                ));
                writer.line("return when (caseIndex) {");
                writer.indent();
                for (idx, case) in cases.iter().enumerate() {
                    let case_name = &case_names[idx];
                    match &case.payload {
                        Some(payload) => {
                            let context = kotlin_string_literal(&format!("{name}.{}", case.name));
                            let dec = self.decode_expr("p", payload, 0)?;
                            writer.line(format!("{idx} -> {{"));
                            writer.indent();
                            writer.line(format!(
                                "val p = {helper}.requiredPayload(payload, {context})"
                            ));
                            writer.line(format!("{self_type}.{case_name}({dec})"));
                            writer.dedent();
                            writer.line("}");
                        }
                        None => {
                            let msg = kotlin_string_literal(&format!(
                                "Unexpected payload for payload-less variant case {name}.{}",
                                case.name
                            ));
                            writer.line(format!("{idx} -> {{"));
                            writer.indent();
                            writer.line(format!("if (payload != null) throw {exc}({msg})"));
                            writer.line(format!("{self_type}.{case_name}"));
                            writer.dedent();
                            writer.line("}");
                        }
                    }
                }
                writer.line(format!(
                    "else -> throw {exc}(\"Invalid variant case index for {name}: $caseIndex\")"
                ));
                writer.dedent();
                writer.line("}");
            }
            SchemaType::Enum { cases, .. } => {
                let case_names = self.enum_entry_idents(cases.iter().map(|c| c.as_str()));
                writer
                    .line("return when (val index = ".to_string() + helper + ".enumCase(value)) {");
                writer.indent();
                for (idx, case_name) in case_names.iter().enumerate() {
                    writer.line(format!("{idx} -> {self_type}.{case_name}"));
                }
                writer.line(format!(
                    "else -> throw {exc}(\"Invalid enum case index for {name}: $index\")"
                ));
                writer.dedent();
                writer.line("}");
            }
            SchemaType::Flags { flags, .. } => {
                let n = flags.len();
                writer.line(format!("val bits = {helper}.flagBits(value)"));
                writer.line(format!(
                    "if (bits.size != {n}) throw {exc}(\"Expected flags {name} with {n} bits, got ${{bits.size}}\")"
                ));
                if n == 0 {
                    writer.line(format!("return {self_type}"));
                } else {
                    let args = (0..n).map(|i| format!("bits[{i}]")).collect::<Vec<_>>();
                    writer.line(format!("return {self_type}({})", args.join(", ")));
                }
            }
            SchemaType::Union { spec, .. } => {
                let branch_names =
                    self.type_member_idents(spec.branches.iter().map(|b| b.tag.as_str()));
                writer.line(format!("val (tag, body) = {helper}.unionBody(value)"));
                writer.line("return when (tag) {");
                writer.indent();
                for (idx, branch) in spec.branches.iter().enumerate() {
                    let tag = kotlin_string_literal(branch.tag.as_str());
                    let dec = self.decode_expr("body", &branch.body, 0)?;
                    writer.line(format!("{tag} -> {self_type}.{}({dec})", branch_names[idx]));
                }
                writer.line(format!(
                    "else -> throw {exc}(\"Unknown union branch tag for {name}: $tag\")"
                ));
                writer.dedent();
                writer.line("}");
            }
            other => bail!("Unexpected non-composite type reached write_decode_fn: {other:?}"),
        }
        writer.dedent();
        writer.line("}");
        Ok(())
    }

    /// A `SchemaValue` expression encoding `val_expr`, a value of the Kotlin
    /// type that [`Self::type_reference`] renders for `typ`.
    pub(crate) fn encode_expr(
        &self,
        val_expr: &str,
        typ: &SchemaType,
        depth: usize,
    ) -> anyhow::Result<String> {
        // `type_reference` rejects a reference that closes a cycle without passing
        // through a named composite. The codec paths must reject it too: without
        // this they recurse until the stack goes, rather than returning an error.
        self.reject_unrepresentable_recursion(typ)?;
        if let Some(name) = self.type_naming.type_name_for_type(typ) {
            match name {
                KotlinTypeName::Remapped(RemappedType::Uuid) => {
                    return Ok(if self.uuid_is_record(typ) {
                        format!(
                            "{sv}.Record(kotlin.collections.listOf({sv}.U64(({val_expr}).highBits.toULong()), {sv}.U64(({val_expr}).lowBits.toULong())))",
                            sv = self.sv()
                        )
                    } else {
                        format!(
                            "{}.UuidVal({val_expr}.highBits, {val_expr}.lowBits)",
                            self.sv()
                        )
                    });
                }
                KotlinTypeName::Derived(name_str) => {
                    if is_named_composite(self.resolve_ref(typ)) {
                        return Ok(format!(
                            "{}.{CODECS_OBJECT}.encode{name_str}({val_expr})",
                            self.client_package()
                        ));
                    }
                }
            }
        }
        self.encode_structural(val_expr, typ, depth)
    }

    /// A Kotlin expression decoding the `SchemaValue` expression `val_expr`.
    pub(crate) fn decode_expr(
        &self,
        val_expr: &str,
        typ: &SchemaType,
        depth: usize,
    ) -> anyhow::Result<String> {
        // `type_reference` rejects a reference that closes a cycle without passing
        // through a named composite. The codec paths must reject it too: without
        // this they recurse until the stack goes, rather than returning an error.
        self.reject_unrepresentable_recursion(typ)?;
        if let Some(name) = self.type_naming.type_name_for_type(typ) {
            match name {
                KotlinTypeName::Remapped(RemappedType::Uuid) => {
                    return Ok(if self.uuid_is_record(typ) {
                        format!("{CODEC_HELPER_OBJECT}.asUuidRecord({val_expr})")
                    } else {
                        format!("{CODEC_HELPER_OBJECT}.asUuid({val_expr})")
                    });
                }
                KotlinTypeName::Derived(name_str) => {
                    if is_named_composite(self.resolve_ref(typ)) {
                        return Ok(format!(
                            "{}.{CODECS_OBJECT}.decode{name_str}({val_expr})",
                            self.client_package()
                        ));
                    }
                }
            }
        }
        self.decode_structural(val_expr, typ, depth)
    }

    fn encode_structural(
        &self,
        val_expr: &str,
        typ: &SchemaType,
        depth: usize,
    ) -> anyhow::Result<String> {
        let sv = self.sv();
        let helper = CODEC_HELPER_OBJECT;
        let exc = self.exception();
        if unstructured_text_restrictions(self.type_naming.graph(), typ)?.is_some() {
            return Ok(format!("{helper}.encodeUnstructuredText({val_expr})"));
        }
        if unstructured_binary_restrictions(self.type_naming.graph(), typ)?.is_some() {
            return Ok(format!("{helper}.encodeUnstructuredBinary({val_expr})"));
        }
        let resolved = self.resolve_ref(typ);
        let e = format!("e{depth}");
        let next = depth + 1;
        let rendered = match resolved {
            SchemaType::Bool { .. } => format!("{sv}.Bool({val_expr})"),
            SchemaType::S8 { .. } => format!("{sv}.S8({val_expr})"),
            SchemaType::S16 { .. } => format!("{sv}.S16({val_expr})"),
            SchemaType::S32 { .. } => format!("{sv}.S32({val_expr})"),
            SchemaType::S64 { .. } => format!("{sv}.S64({val_expr})"),
            SchemaType::U8 { .. } => format!("{sv}.U8({val_expr})"),
            SchemaType::U16 { .. } => format!("{sv}.U16({val_expr})"),
            SchemaType::U32 { .. } => format!("{sv}.U32({val_expr})"),
            SchemaType::U64 { .. } => format!("{sv}.U64({val_expr})"),
            SchemaType::F32 { .. } => format!("{sv}.F32({val_expr})"),
            SchemaType::F64 { .. } => format!("{sv}.F64({val_expr})"),
            SchemaType::Char { .. } => format!("{helper}.encodeChar({val_expr})"),
            SchemaType::String { .. } => format!("{sv}.Str({val_expr})"),
            SchemaType::Option { inner, .. } => {
                let inner_enc = self.encode_expr(&e, inner, next)?;
                format!("{sv}.OptionVal(({val_expr})?.let {{ {e} -> {inner_enc} }})")
            }
            SchemaType::List { element, .. } => {
                let inner_enc = self.encode_expr(&e, element, next)?;
                format!("{sv}.ListVal(({val_expr}).map {{ {e} -> {inner_enc} }})")
            }
            SchemaType::FixedList {
                element, length, ..
            } => {
                let inner_enc = self.encode_expr(&e, element, next)?;
                let elems = format!("elems{depth}");
                format!(
                    "run {{\n    val {elems} = ({val_expr}).map {{ {e} -> {inner_enc} }}\n    if ({elems}.size != {length}) throw {exc}(\"Expected fixed-list of length {length}, got ${{{elems}.size}}\")\n    {sv}.FixedListVal({elems})\n}}"
                )
            }
            SchemaType::Map { key, value, .. } => {
                let k = format!("k{depth}");
                let v = format!("v{depth}");
                let key_enc = self.encode_expr(&k, key, next)?;
                let val_enc = self.encode_expr(&v, value, next)?;
                format!(
                    "{sv}.MapVal(({val_expr}).map {{ ({k}, {v}) -> kotlin.Pair({key_enc}, {val_enc}) }})"
                )
            }
            SchemaType::Tuple { elements, .. } => self.encode_tuple(val_expr, elements, depth)?,
            SchemaType::Result { spec, .. } => {
                let r = format!("r{depth}");
                let either = self.runtime.either;
                let ok_arm = match spec.ok.as_deref() {
                    Some(ok_type) => {
                        let enc = self.encode_expr(&format!("{r}.value"), ok_type, next)?;
                        format!("{sv}.ResultVal(true, {enc})")
                    }
                    None => format!("{sv}.ResultVal(true, null)"),
                };
                let err_arm = match spec.err.as_deref() {
                    Some(err_type) => {
                        let enc = self.encode_expr(&format!("{r}.value"), err_type, next)?;
                        format!("{sv}.ResultVal(false, {enc})")
                    }
                    None => format!("{sv}.ResultVal(false, null)"),
                };
                format!(
                    "when (val {r} = {val_expr}) {{\n    is {either}.Right -> {ok_arm}\n    is {either}.Left -> {err_arm}\n}}"
                )
            }
            SchemaType::Path { .. } => format!("{sv}.PathVal({val_expr})"),
            SchemaType::Url { .. } => format!("{sv}.UrlVal({val_expr})"),
            SchemaType::Quantity { spec, .. } => format!(
                "{helper}.quantityValue({val_expr}, {})",
                quantity_spec_arguments(spec)
            ),
            SchemaType::Uuid { .. } => {
                format!("{sv}.UuidVal({val_expr}.highBits, {val_expr}.lowBits)")
            }
            SchemaType::Datetime { .. } => {
                format!("{sv}.DatetimeVal({val_expr}.seconds, {val_expr}.nanoseconds)")
            }
            SchemaType::Duration { .. } => {
                format!("{helper}.encodeDuration({val_expr})")
            }
            SchemaType::Record { .. }
            | SchemaType::Variant { .. }
            | SchemaType::Enum { .. }
            | SchemaType::Flags { .. }
            | SchemaType::Union { .. } => bail!(
                "Composite schema type reached encode_structural without a registered name: {resolved:?}"
            ),
            SchemaType::Stream { inner, .. } if self.mode == KotlinBridgeMode::ExternalRest => {
                let element = Self::stream_element(inner.as_deref())?;
                let item = format!("item{depth}");
                let encoded = self.encode_expr(&item, element, next)?;
                let lane = self.stream_lane(element);
                format!("{STREAM_SESSION}.input({val_expr}, {{ {item} -> {encoded} }}, \"{lane}\")")
            }
            SchemaType::Ref { .. } => unreachable!("Ref was resolved to its body via resolve_ref"),
            other => bail!("{}", unsupported_message(other)),
        };
        Ok(rendered)
    }

    fn decode_structural(
        &self,
        val_expr: &str,
        typ: &SchemaType,
        depth: usize,
    ) -> anyhow::Result<String> {
        let helper = CODEC_HELPER_OBJECT;
        let exc = self.exception();
        if let Some(restrictions) = unstructured_text_restrictions(self.type_naming.graph(), typ)? {
            let allowed = restrictions
                .languages
                .as_deref()
                .unwrap_or_default()
                .iter()
                .map(|code| kotlin_string_literal(code))
                .collect::<Vec<_>>()
                .join(", ");
            return Ok(format!(
                "{helper}.unstructuredText({val_expr}, kotlin.collections.listOf({allowed}))"
            ));
        }
        if let Some(restrictions) = unstructured_binary_restrictions(self.type_naming.graph(), typ)?
        {
            let allowed = restrictions
                .mime_types
                .as_deref()
                .unwrap_or_default()
                .iter()
                .map(|code| kotlin_string_literal(code))
                .collect::<Vec<_>>()
                .join(", ");
            return Ok(format!(
                "{helper}.unstructuredBinary({val_expr}, kotlin.collections.listOf({allowed}))"
            ));
        }
        let resolved = self.resolve_ref(typ);
        let e = format!("e{depth}");
        let next = depth + 1;
        let rendered = match resolved {
            SchemaType::Bool { .. } => format!("{helper}.asBool({val_expr})"),
            SchemaType::S8 { .. } => format!("{helper}.asByte({val_expr})"),
            SchemaType::S16 { .. } => format!("{helper}.asShort({val_expr})"),
            SchemaType::S32 { .. } => format!("{helper}.asInt({val_expr})"),
            SchemaType::S64 { .. } => format!("{helper}.asLong({val_expr})"),
            SchemaType::U8 { .. } => format!("{helper}.asUByte({val_expr})"),
            SchemaType::U16 { .. } => format!("{helper}.asUShort({val_expr})"),
            SchemaType::U32 { .. } => format!("{helper}.asUInt({val_expr})"),
            SchemaType::U64 { .. } => format!("{helper}.asULong({val_expr})"),
            SchemaType::F32 { .. } => format!("{helper}.asFloat({val_expr})"),
            SchemaType::F64 { .. } => format!("{helper}.asDouble({val_expr})"),
            SchemaType::Char { .. } => format!("{helper}.asChar({val_expr})"),
            SchemaType::String { .. } => format!("{helper}.asString({val_expr})"),
            SchemaType::Option { inner, .. } => {
                let inner_dec = self.decode_expr(&e, inner, next)?;
                format!("{helper}.optionValue({val_expr})?.let {{ {e} -> {inner_dec} }}")
            }
            SchemaType::List { element, .. } => {
                let inner_dec = self.decode_expr(&e, element, next)?;
                format!("{helper}.listElements({val_expr}).map {{ {e} -> {inner_dec} }}")
            }
            SchemaType::FixedList {
                element, length, ..
            } => {
                let inner_dec = self.decode_expr(&e, element, next)?;
                let elems = format!("elems{depth}");
                format!(
                    "run {{\n    val {elems} = {helper}.listElements({val_expr})\n    if ({elems}.size != {length}) throw {exc}(\"Expected fixed-list of length {length}, got ${{{elems}.size}}\")\n    {elems}.map {{ {e} -> {inner_dec} }}\n}}"
                )
            }
            SchemaType::Map { key, value, .. } => {
                let me = format!("me{depth}");
                let key_dec = self.decode_expr(&format!("{me}.first"), key, next)?;
                let val_dec = self.decode_expr(&format!("{me}.second"), value, next)?;
                format!(
                    "{helper}.mapEntries({val_expr}).associate {{ {me} -> kotlin.Pair({key_dec}, {val_dec}) }}"
                )
            }
            SchemaType::Tuple { elements, .. } => self.decode_tuple(val_expr, elements, depth)?,
            SchemaType::Result { spec, .. } => {
                let either = self.runtime.either;
                let r = format!("r{depth}");
                let ok_arm = match spec.ok.as_deref() {
                    Some(ok_type) => {
                        let dec = self.decode_expr("p", ok_type, next)?;
                        format!(
                            "{{ val p = {helper}.requiredPayload({r}.inner, \"result ok\"); {either}.Right({dec}) }}"
                        )
                    }
                    None => format!(
                        "{{ if ({r}.inner != null) throw {exc}(\"Unexpected payload for unit result ok\"); {either}.Right(kotlin.Unit) }}"
                    ),
                };
                let err_arm = match spec.err.as_deref() {
                    Some(err_type) => {
                        let dec = self.decode_expr("p", err_type, next)?;
                        format!(
                            "{{ val p = {helper}.requiredPayload({r}.inner, \"result err\"); {either}.Left({dec}) }}"
                        )
                    }
                    None => format!(
                        "{{ if ({r}.inner != null) throw {exc}(\"Unexpected payload for unit result err\"); {either}.Left(kotlin.Unit) }}"
                    ),
                };
                format!(
                    "{helper}.resultValue({val_expr}).let {{ {r} ->\n    if ({r}.ok) {ok_arm} else {err_arm}\n}}"
                )
            }
            SchemaType::Path { .. } => format!("{helper}.asPath({val_expr})"),
            SchemaType::Url { .. } => format!("{helper}.asUrl({val_expr})"),
            SchemaType::Quantity { spec, .. } => format!(
                "{helper}.asQuantity({val_expr}, {})",
                quantity_spec_arguments(spec)
            ),
            SchemaType::Uuid { .. } => format!("{helper}.asUuid({val_expr})"),
            SchemaType::Datetime { .. } => format!("{helper}.asDatetime({val_expr})"),
            SchemaType::Duration { .. } => format!("{helper}.asDuration({val_expr})"),
            SchemaType::Record { .. }
            | SchemaType::Variant { .. }
            | SchemaType::Enum { .. }
            | SchemaType::Flags { .. }
            | SchemaType::Union { .. } => bail!(
                "Composite schema type reached decode_structural without a registered name: {resolved:?}"
            ),
            SchemaType::Stream { inner, .. } if self.mode == KotlinBridgeMode::ExternalRest => {
                let element = Self::stream_element(inner.as_deref())?;
                let item = format!("item{depth}");
                let decoded = self.decode_expr(&item, element, next)?;
                let lane = self.stream_lane(element);
                format!(
                    "{STREAM_SESSION}.output({val_expr}, {{ {item} -> {decoded} }}, \"{lane}\")"
                )
            }
            SchemaType::Ref { .. } => unreachable!("Ref was resolved to its body via resolve_ref"),
            other => bail!("{}", unsupported_message(other)),
        };
        Ok(rendered)
    }

    fn encode_tuple(
        &self,
        val_expr: &str,
        elements: &[SchemaType],
        depth: usize,
    ) -> anyhow::Result<String> {
        let sv = self.sv();
        if elements.is_empty() {
            return Ok(format!("{sv}.TupleVal(kotlin.collections.emptyList())"));
        }
        let t = format!("t{depth}");
        let next = depth + 1;
        let mut lines = vec![format!("    val {t} = {val_expr}")];
        let mut names = Vec::new();
        for (idx, element) in elements.iter().enumerate() {
            let enc = self.encode_expr(
                &format!("{t}.{}", tuple_accessor(elements.len(), idx)),
                element,
                next,
            )?;
            lines.push(format!("    val te{idx} = {enc}"));
            names.push(format!("te{idx}"));
        }
        lines.push(format!(
            "    {sv}.TupleVal(kotlin.collections.listOf({}))",
            names.join(", ")
        ));
        Ok(format!("run {{\n{}\n}}", lines.join("\n")))
    }

    fn decode_tuple(
        &self,
        val_expr: &str,
        elements: &[SchemaType],
        depth: usize,
    ) -> anyhow::Result<String> {
        let helper = CODEC_HELPER_OBJECT;
        let exc = self.exception();
        let elems = format!("elems{depth}");
        if elements.is_empty() {
            return Ok(format!(
                "run {{\n    val {elems} = {helper}.tupleElements({val_expr})\n    if ({elems}.isNotEmpty()) throw {exc}(\"Expected empty tuple, got ${{{elems}.size}} elements\")\n    kotlin.Unit\n}}"
            ));
        }
        let n = elements.len();
        let next = depth + 1;
        let mut lines = vec![
            format!("    val {elems} = {helper}.tupleElements({val_expr})"),
            format!(
                "    if ({elems}.size != {n}) throw {exc}(\"Expected tuple of arity {n}, got ${{{elems}.size}}\")"
            ),
        ];
        let mut names = Vec::new();
        for (idx, element) in elements.iter().enumerate() {
            let dec = self.decode_expr(&format!("{elems}[{idx}]"), element, next)?;
            lines.push(format!("    val te{idx} = {dec}"));
            names.push(format!("te{idx}"));
        }
        let ctor = tuple_constructor(self, n);
        lines.push(format!("    {ctor}({})", names.join(", ")));
        Ok(format!("run {{\n{}\n}}", lines.join("\n")))
    }

    // --- Type references ----------------------------------------------------

    /// Renders the Kotlin type of `typ`, fully qualified.
    pub(crate) fn type_reference(&self, typ: &SchemaType) -> anyhow::Result<String> {
        // The unstructured check comes first: an unstructured value is a variant, so
        // a *named* def wrapping one would otherwise be rendered as an ordinary sealed
        // class, and rendering its inline case would then bail with a message telling
        // the author to wrap it in an unstructured variant -- which is what they did.
        if unstructured_text_restrictions(self.type_naming.graph(), typ)?.is_some() {
            return Ok(self.runtime.unstructured_text.to_string());
        }
        if unstructured_binary_restrictions(self.type_naming.graph(), typ)?.is_some() {
            return Ok(self.runtime.unstructured_binary.to_string());
        }
        if let Some(name) = self.type_naming.type_name_for_type(typ) {
            match name {
                KotlinTypeName::Remapped(_) => {
                    self.check_uuid_shape(typ)?;
                    return Ok(self.runtime.uuid.to_string());
                }
                KotlinTypeName::Derived(name_str) => {
                    if is_named_composite(self.resolve_ref(typ)) {
                        return Ok(self.qualified(name_str));
                    }
                }
            }
        }
        self.reject_unrepresentable_recursion(typ)?;
        let resolved = self.resolve_ref(typ);
        match resolved {
            SchemaType::Bool { .. } => Ok("kotlin.Boolean".to_string()),
            SchemaType::S8 { .. } => Ok("kotlin.Byte".to_string()),
            SchemaType::S16 { .. } => Ok("kotlin.Short".to_string()),
            SchemaType::S32 { .. } => Ok("kotlin.Int".to_string()),
            SchemaType::S64 { .. } => Ok("kotlin.Long".to_string()),
            SchemaType::U8 { .. } => Ok("kotlin.UByte".to_string()),
            SchemaType::U16 { .. } => Ok("kotlin.UShort".to_string()),
            SchemaType::U32 { .. } => Ok("kotlin.UInt".to_string()),
            SchemaType::U64 { .. } => Ok("kotlin.ULong".to_string()),
            SchemaType::F32 { .. } => Ok("kotlin.Float".to_string()),
            SchemaType::F64 { .. } => Ok("kotlin.Double".to_string()),
            SchemaType::Char { .. } => Ok("kotlin.Char".to_string()),
            SchemaType::String { .. } | SchemaType::Path { .. } | SchemaType::Url { .. } => {
                Ok("kotlin.String".to_string())
            }
            SchemaType::Quantity { .. } => Ok(self.runtime.quantity.to_string()),
            SchemaType::Option { inner, .. } => {
                if matches!(self.resolve_ref(inner), SchemaType::Option { .. }) {
                    bail!(
                        "A nested option cannot be represented in the Kotlin bridge: a nullable of a nullable collapses to one level"
                    );
                }
                Ok(format!("{}?", self.type_reference(inner)?))
            }
            SchemaType::List { element, .. } | SchemaType::FixedList { element, .. } => Ok(
                format!("kotlin.collections.List<{}>", self.type_reference(element)?),
            ),
            SchemaType::Tuple { elements, .. } => self.tuple_type(elements),
            SchemaType::Map { key, value, .. } => Ok(format!(
                "kotlin.collections.Map<{}, {}>",
                self.type_reference(key)?,
                self.type_reference(value)?
            )),
            SchemaType::Result { spec, .. } => {
                let ok_type = match spec.ok.as_deref() {
                    Some(ty) => self.type_reference(ty)?,
                    None => "kotlin.Unit".to_string(),
                };
                let err_type = match spec.err.as_deref() {
                    Some(ty) => self.type_reference(ty)?,
                    None => "kotlin.Unit".to_string(),
                };
                Ok(format!("{}<{err_type}, {ok_type}>", self.runtime.either))
            }
            SchemaType::Uuid { .. } => Ok(self.runtime.uuid.to_string()),
            SchemaType::Datetime { .. } => Ok(self.runtime.datetime.to_string()),
            SchemaType::Duration { .. } => Ok("kotlin.time.Duration".to_string()),
            SchemaType::Record { .. }
            | SchemaType::Variant { .. }
            | SchemaType::Enum { .. }
            | SchemaType::Flags { .. }
            | SchemaType::Union { .. } => bail!(
                "Composite schema type reached type_reference without a registered name: {resolved:?}"
            ),
            SchemaType::Stream { inner, .. } if self.mode == KotlinBridgeMode::ExternalRest => {
                let element = Self::stream_element(inner.as_deref())?;
                Ok(format!("{AGENT_STREAM}<{}>", self.type_reference(element)?))
            }
            SchemaType::Ref { .. } => unreachable!("Ref was resolved to its body via resolve_ref"),
            other => bail!("{}", unsupported_message(other)),
        }
    }

    fn stream_element(inner: Option<&SchemaType>) -> anyhow::Result<&SchemaType> {
        inner.ok_or_else(|| {
            anyhow::anyhow!(
                "Kotlin external streams require an element schema; declare the stream with an element type"
            )
        })
    }

    fn stream_lane(&self, element: &SchemaType) -> &'static str {
        match self.resolve_ref(element) {
            SchemaType::U8 { .. } => "u8",
            _ => "json",
        }
    }

    fn tuple_type(&self, elements: &[SchemaType]) -> anyhow::Result<String> {
        let types = elements
            .iter()
            .map(|item| self.type_reference(item))
            .collect::<anyhow::Result<Vec<_>>>()?;
        match types.len() {
            0 => Ok("kotlin.Unit".to_string()),
            2 => Ok(format!("kotlin.Pair<{}>", types.join(", "))),
            3 => Ok(format!("kotlin.Triple<{}>", types.join(", "))),
            n => {
                if n > TUPLE_ARITY_RESERVED_MAX {
                    bail!(
                        "A tuple of arity {n} is not supported by the Kotlin bridge: only Tuple1 and Tuple4..Tuple{TUPLE_ARITY_RESERVED_MAX} are reserved against schema type names, so a wider one could collide with a generated type"
                    );
                }
                self.tuple_arities.borrow_mut().insert(n);
                Ok(format!(
                    "{}<{}>",
                    self.qualified(&format!("Tuple{n}")),
                    types.join(", ")
                ))
            }
        }
    }

    /// Whether the `uuid.Uuid` definition is a record of two `u64` halves, as the Scala SDK registers it, and not the `uuid` primitive
    /// that the Rust SDK registers. Both map to the runtime `Uuid`, but they travel as different value nodes.
    ///
    /// The generated encode hard-codes the two halves in (high, low) order, so a
    /// record of any other shape would be encoded wrongly and silently. Only the
    /// two shapes the SDKs actually register are accepted; [`check_uuid_shape`]
    /// rejects the rest.
    fn uuid_is_record(&self, typ: &SchemaType) -> bool {
        matches!(self.resolve_ref(typ), SchemaType::Record { .. })
    }

    /// Rejects a `uuid.Uuid` definition whose body is neither the `uuid` primitive
    /// nor a record of exactly two `u64` fields.
    fn check_uuid_shape(&self, typ: &SchemaType) -> anyhow::Result<()> {
        match self.resolve_ref(typ) {
            SchemaType::Uuid { .. } => Ok(()),
            SchemaType::Record { fields, .. }
                if fields.len() == 2
                    && fields
                        .iter()
                        .all(|f| matches!(f.body, SchemaType::U64 { .. })) =>
            {
                Ok(())
            }
            other => bail!(
                "The `uuid.Uuid` definition must be the `uuid` primitive or a record of two u64 halves, because the Kotlin bridge encodes it as (high, low); found {other:?}"
            ),
        }
    }

    /// Rejects a reference that closes a cycle without passing through a named
    /// composite. Such a type has no Kotlin representation, and every renderer
    /// that walks into it would recurse without bound.
    fn reject_unrepresentable_recursion(&self, typ: &SchemaType) -> anyhow::Result<()> {
        if self.type_naming.is_recursive_ref(typ) && !is_named_composite(self.resolve_ref(typ)) {
            bail!(
                "Recursive non-composite type alias cannot be represented in the Kotlin bridge: {typ:?}"
            );
        }
        Ok(())
    }

    pub(crate) fn resolve_ref<'a>(&'a self, typ: &'a SchemaType) -> &'a SchemaType {
        self.type_naming
            .graph()
            .resolve_ref(typ)
            .expect("bridge schemas contain only resolvable references")
    }
}

/// Name of the generated client object, e.g. `foo-agent` -> `FooAgentClient`.
pub(crate) fn client_object_name(agent_type: &AgentTypeSchema) -> String {
    format!(
        "{}Client",
        agent_type.type_name.as_str().to_upper_camel_case()
    )
}

/// Name of the generated remote class, e.g. `foo-agent` -> `FooAgentRemote`.
pub(crate) fn remote_class_name(agent_type: &AgentTypeSchema) -> String {
    format!(
        "{}Remote",
        agent_type.type_name.as_str().to_upper_camel_case()
    )
}

/// The accessor of element `idx` in a tuple of `arity` elements.
fn tuple_accessor(arity: usize, idx: usize) -> String {
    match arity {
        2 | 3 => ["first", "second", "third"][idx].to_string(),
        _ => format!("v{}", idx + 1),
    }
}

fn tuple_constructor(generator: &KotlinBridgeGenerator, arity: usize) -> String {
    match arity {
        2 => "kotlin.Pair".to_string(),
        3 => "kotlin.Triple".to_string(),
        n => {
            generator.tuple_arities.borrow_mut().insert(n);
            generator.qualified(&format!("Tuple{n}"))
        }
    }
}

/// A quantity's base unit and allowed suffixes, as the two trailing arguments of a codec call. The
/// spec's `min` and `max` are schema metadata the codecs do not read.
fn quantity_spec_arguments(spec: &golem_common::schema::schema_type::QuantitySpec) -> String {
    format!(
        "{}, listOf({})",
        kotlin_string_literal(&spec.base_unit),
        spec.allowed_suffixes
            .iter()
            .map(|s| kotlin_string_literal(s))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn unsupported_message(typ: &SchemaType) -> String {
    match typ {
        SchemaType::Text { .. } | SchemaType::Binary { .. } => format!(
            "Bare text/binary rich scalars have no Kotlin bridge representation; wrap them in the unstructured text/binary variant ({typ:?})"
        ),
        SchemaType::Stream { .. } => {
            "Streams are not supported by the Kotlin bridge generator".to_string()
        }
        SchemaType::Secret { .. }
        | SchemaType::QuotaToken { .. }
        | SchemaType::PermissionCard { .. }
        | SchemaType::Future { .. } => {
            format!("The Kotlin bridge generator does not support this schema type: {typ:?}")
        }
        other => format!("Unexpected schema type in the Kotlin bridge generator: {other:?}"),
    }
}

pub(crate) fn is_named_composite(resolved: &SchemaType) -> bool {
    matches!(
        resolved,
        SchemaType::Record { .. }
            | SchemaType::Variant { .. }
            | SchemaType::Enum { .. }
            | SchemaType::Flags { .. }
            | SchemaType::Union { .. }
    )
}

/// `text` made safe inside a block comment: Kotlin block comments nest, so both `/*` and `*/` are broken up.
pub(crate) fn kdoc_safe(text: &str) -> String {
    text.replace("*/", "*&#47;").replace("/*", "&#47;*")
}

/// Renders `value` as a plain double-quoted Kotlin string literal. `$` is
/// escaped so it is never read as a template.
pub(crate) fn kotlin_string_literal(value: &str) -> String {
    let mut escaped = String::with_capacity(value.len() + 2);
    escaped.push('"');
    for ch in value.chars() {
        match ch {
            '\\' => escaped.push_str("\\\\"),
            '"' => escaped.push_str("\\\""),
            '$' => escaped.push_str("\\$"),
            '\n' => escaped.push_str("\\n"),
            '\r' => escaped.push_str("\\r"),
            '\t' => escaped.push_str("\\t"),
            c if (c as u32) < 0x20 => escaped.push_str(&format!("\\u{:04x}", c as u32)),
            c => escaped.push(c),
        }
    }
    escaped.push('"');
    escaped
}

