    /// `FutureInvokeResult.cancel` is not a destructor: the WIT declares
    /// `cancel: func()` beside a separate `[resource-drop]`, and the SDK leaves
    /// `cancel` unguarded. A cancelled future must therefore still be dropped,
    /// or its handle-table entry outlives the call.
    #[test]
    fn cancelling_a_future_also_releases_its_handle() {
        let code = guest_source(rich_agent());
        let body = remote_future_source(&code);
        assert!(
            body.contains("future.cancel()") && body.contains("future.close()"),
            "cancel() must release the handle it cancels:\n{body}"
        );
        let cancel = body
            .split_once("fun cancel()")
            .expect("a cancel method")
            .1
            .split_once("\n    }")
            .expect("a cancel body")
            .0;
        assert!(
            cancel.contains("future.cancel()") && cancel.contains("future.close()"),
            "cancel() cancels but never closes:\n{cancel}"
        );
    }

    /// Releasing the handle twice, or using it after release, passes a dropped
    /// handle to the host. One `released` flag must guard every path.
    #[test]
    fn a_future_is_released_at_most_once_and_cannot_be_used_afterwards() {
        let code = guest_source(rich_agent());
        let body = remote_future_source(&code);
        assert!(
            body.contains("private var released = false"),
            "the future needs a released flag:\n{body}"
        );
        for method in ["fun cancel()", "override fun close()"] {
            let tail = body.split_once(method).expect("the method").1;
            let guarded = tail
                .split_once("\n    }")
                .expect("the method body")
                .0
                .contains("released");
            assert!(guarded, "{method} does not consult released:\n{body}");
        }
        let await_body = body
            .split_once("fun await()")
            .expect("an await method")
            .1
            .split_once("\n    }")
            .expect("an await body")
            .0;
        assert!(
            await_body.contains("released"),
            "await() must refuse a released future rather than call get() on a dropped handle:\n{await_body}"
        );
    }

    /// The generated `RemoteFuture` class body, for the lifecycle assertions.
    fn remote_future_source(code: &str) -> String {
        let start = code
            .find("class RemoteFuture<R>")
            .expect("a RemoteFuture class");
        let rest = &code[start..];
        let end = rest.find("\n}\n").map(|i| i + 2).unwrap_or(rest.len());
        rest[..end].to_string()
    }
