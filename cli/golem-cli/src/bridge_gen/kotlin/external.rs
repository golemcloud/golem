//! External-mode Kotlin client: a typed surface over the embedded REST runtime (`golem.bridge.runtime`), for programs that run
//! outside Golem on the JVM.

use crate::bridge_gen::kotlin::guest::{MethodNames, indent_tail};
use crate::bridge_gen::kotlin::kotlin_writer::KotlinWriter;
use crate::bridge_gen::kotlin::{
    KotlinBridgeGenerator, client_object_name, kotlin_string_literal, remote_class_name,
};
use crate::fs;
use anyhow::{Context, bail};
use camino::Utf8Path;
use golem_common::model::agent::AgentMode;
use golem_common::schema::{AgentMethodSchema, OutputSchema};
use include_dir::{Dir, include_dir};

/// The embedded REST runtime, written verbatim into every generated external project. Each file already carries its
/// `golem/bridge/runtime/...` relative path.
static RUNTIME_DIR: Dir<'static> =
    include_dir!("$CARGO_MANIFEST_DIR/src/bridge_gen/kotlin/runtime");

const RT: &str = "golem.bridge.runtime";
const FUTURE: &str = "java.util.concurrent.CompletableFuture";
const MODE_AWAIT: &str = "await";
const MODE_SCHEDULE: &str = "schedule";

/// `settings.gradle.kts` of a generated external project.
pub(super) fn settings_gradle(name: &str, kotlin_version: &str) -> String {
    format!(
        "pluginManagement {{\n    repositories {{\n        gradlePluginPortal()\n        mavenCentral()\n    }}\n    plugins {{\n        kotlin(\"jvm\") version \"{kotlin_version}\"\n    }}\n}}\n\nrootProject.name = \"{name}\"\n"
    )
}

/// `build.gradle.kts` of a generated external project: a Kotlin/JVM library with no dependency beyond the JDK.
pub(super) fn build_gradle() -> String {
    "plugins {\n    kotlin(\"jvm\")\n}\n\ngroup = \"golem.bridge\"\nversion = \"0.0.1\"\n\nrepositories {\n    mavenCentral()\n}\n".to_string()
}

/// Writes the embedded runtime sources below `source_root`.
pub(super) fn write_runtime(source_root: &Utf8Path) -> anyhow::Result<()> {
    write_dir(&RUNTIME_DIR, source_root)
}

fn write_dir(dir: &Dir<'_>, dest: &Utf8Path) -> anyhow::Result<()> {
    for file in dir.files() {
        let relative = Utf8Path::from_path(file.path()).with_context(|| {
            format!(
                "Embedded runtime path is not valid UTF-8: {:?}",
                file.path()
            )
        })?;
        let contents = file.contents_utf8().with_context(|| {
            format!(
                "Embedded runtime file is not valid UTF-8: {:?}",
                file.path()
            )
        })?;
        fs::write_str(dest.join(relative), contents)?;
    }
    for sub in dir.dirs() {
        write_dir(sub, dest)?;
    }
    Ok(())
}

impl KotlinBridgeGenerator {
    /// The full source file of the external client: package, generated types, codecs, the client object and the remote class.
    pub(crate) fn generate_external_client_source(&self) -> anyhow::Result<String> {
        let mut body = KotlinWriter::new();
        self.write_external_client_object(&mut body)?;
        let mut types = KotlinWriter::new();
        self.write_type_definitions(&mut types)?;
        self.write_codecs(&mut types)?;
        let mut tuples = KotlinWriter::new();
        self.write_tuple_types(&mut tuples);

        let mut out = KotlinWriter::new();
        out.line("// Generated by golem-cli. Do not edit.");
        out.line("@file:Suppress(\"unused\", \"RedundantVisibilityModifier\", \"UNCHECKED_CAST\", \"NAME_SHADOWING\")");
        out.blank();
        out.line(format!("package {}", self.client_package()));
        out.blank();
        out.line("import kotlin.time.toDuration");
        out.blank();
        out.line(types.finish());
        out.line(tuples.finish());
        out.line(body.finish());
        out.blank();
        out.line(self.codec_helper_source());
        Ok(out.finish())
    }

    fn write_external_client_object(&self, writer: &mut KotlinWriter) -> anyhow::Result<()> {
        let object_name = client_object_name(&self.agent_type);
        let remote_name = remote_class_name(&self.agent_type);
        let type_name = self.agent_type.type_name.as_str();

        writer.line(format!(
            "/** Typed client of the agent type `{}`. */",
            crate::bridge_gen::kotlin::kdoc_safe(type_name)
        ));
        writer.line(format!("object {object_name} {{"));
        writer.indent();
        writer.line(format!(
            "const val agentTypeName: kotlin.String = {}",
            kotlin_string_literal(type_name)
        ));
        writer.blank();
        writer.doc("Points every generated client of this project at a server, application and environment.");
        writer.line(format!(
            "fun configure(server: {RT}.GolemServer, appName: kotlin.String, envName: kotlin.String) =\n    {RT}.Configuration.configure(server, appName, envName)"
        ));
        writer.blank();
        self.write_external_constructors(writer, &remote_name)?;
        writer.dedent();
        writer.line("}");
        writer.blank();
        self.write_external_remote_class(writer, &remote_name)
    }

    fn write_external_constructors(
        &self,
        writer: &mut KotlinWriter,
        remote_name: &str,
    ) -> anyhow::Result<()> {
        // A local config override travels as schema-directed `render` JSON, which the
        // embedded runtime cannot produce; only the self-describing form is implemented.
        // Generating the plain constructors anyway would start the agent on its declared
        // defaults with nothing to show for the override, so refuse instead. A secret
        // declaration is resolved by the environment and needs nothing from the caller.
        let local_configs = self.local_configs();
        if !local_configs.is_empty() {
            let paths = local_configs
                .iter()
                .map(|config| config.path.join("."))
                .collect::<Vec<_>>()
                .join(", ");
            bail!(
                "The agent type `{}` declares local config ({paths}), which the Kotlin external bridge cannot send. \
                 Use a guest-mode bridge, or set the value in the environment's agent config.",
                self.agent_type.type_name
            );
        }
        let input = &self.agent_type.constructor.input_schema;
        let params = self.input_params(input)?;
        let decls = params
            .iter()
            .map(|(n, t)| format!("{n}: {t}"))
            .collect::<Vec<_>>()
            .join(", ");
        let args = params
            .iter()
            .map(|(n, _)| n.clone())
            .collect::<Vec<_>>()
            .join(", ");
        let input_expr = self.input_record_expr(input)?;
        let uuid = self.runtime.uuid;
        let durable = self.agent_type.mode == AgentMode::Durable;
        let join = |parts: &[&str]| {
            parts
                .iter()
                .filter(|s| !s.is_empty())
                .copied()
                .collect::<Vec<_>>()
                .join(", ")
        };

        writer.line(format!(
            "private fun golemInput({decls}): {} = {input_expr}",
            self.sv()
        ));
        writer.blank();
        if durable {
            writer.line(format!(
                "private fun golemResolve(golemInput: {sv}, golemPhantom: {uuid}?): {remote_name} {{\n    val configuration = {RT}.Configuration.get()\n    val phantomText = golemPhantom?.toStandardString()\n    val agentId = {RT}.Bridge.createAgent(configuration, agentTypeName, golemInput, phantomText)\n    return {remote_name}({RT}.ResolvedAgent(configuration, agentTypeName, golemInput, phantomText, agentId))\n}}",
                sv = self.sv()
            ));
        } else {
            writer.line(format!(
                "private fun golemResolve(golemInput: {sv}, golemPhantom: {uuid}?): {remote_name} =\n    {remote_name}({RT}.ResolvedAgent({RT}.Configuration.get(), agentTypeName, golemInput, golemPhantom?.toStandardString(), null))",
                sv = self.sv()
            ));
        }
        writer.blank();
        if durable {
            writer.doc("Connects to the durable agent with these constructor parameters, creating it if it does not exist.\n\nThrows a bridge exception when the server refuses.");
            writer.line(format!("fun get({decls}): {remote_name} ="));
            writer.line(format!("    golemResolve(golemInput({args}), null)"));
            writer.blank();
            writer.doc("Connects to the phantom instance `phantom` of the agent.");
            writer.line(format!(
                "fun getPhantom({}): {remote_name} =",
                join(&[&decls, &format!("phantom: {uuid}")])
            ));
            writer.line(format!("    golemResolve(golemInput({args}), phantom)"));
            writer.blank();
            writer.doc("Connects to a new phantom instance of the agent.");
            writer.line(format!("fun newPhantom({decls}): {remote_name} ="));
            writer.line(format!(
                "    golemResolve(golemInput({args}), {uuid}.random())"
            ));
        } else {
            writer.doc(
                "Creates a handle to the ephemeral agent. Every call runs on a fresh instance.",
            );
            writer.line(format!("fun newPhantom({decls}): {remote_name} ="));
            writer.line(format!("    golemResolve(golemInput({args}), null)"));
        }
        Ok(())
    }

    fn write_external_remote_class(
        &self,
        writer: &mut KotlinWriter,
        remote_name: &str,
    ) -> anyhow::Result<()> {
        let methods = &self.agent_type.methods;
        let names = self.method_names(methods);
        let durable = self.agent_type.mode == AgentMode::Durable;

        writer.line(format!(
            "/** A handle to one instance of the agent `{}`. */",
            crate::bridge_gen::kotlin::kdoc_safe(self.agent_type.type_name.as_str())
        ));
        writer.line(format!(
            "class {remote_name} internal constructor(private val golemResolved: {RT}.ResolvedAgent) {{"
        ));
        writer.indent();
        writer.line(format!(
            "val agentTypeName: kotlin.String get() = {}.agentTypeName",
            client_object_name(&self.agent_type)
        ));
        if durable {
            writer.line(format!(
                "val agentId: {RT}.AgentId get() = golemResolved.agentId ?: throw {RT}.BridgeException(\"The agent has not been resolved\")"
            ));
        }
        writer.blank();
        for (idx, method) in methods.iter().enumerate() {
            self.write_external_method(writer, idx, method, &names[idx])?;
            writer.blank();
        }
        writer.dedent();
        writer.line("}");
        Ok(())
    }

    fn write_external_method(
        &self,
        writer: &mut KotlinWriter,
        index: usize,
        method: &AgentMethodSchema,
        names: &MethodNames,
    ) -> anyhow::Result<()> {
        let streaming = method.uses_streams(&self.agent_type.schema);
        let ephemeral = self.agent_type.mode == AgentMode::Ephemeral;
        let params = self.input_params(&method.input_schema)?;
        let decls = params
            .iter()
            .map(|(n, t)| format!("{n}: {t}"))
            .collect::<Vec<_>>()
            .join(", ");
        let input_expr = self.input_record_expr(&method.input_schema)?;
        let wire = kotlin_string_literal(&method.name);
        let (ret_ty, decode) = match &method.output_schema {
            OutputSchema::Unit => ("kotlin.Unit".to_string(), None),
            OutputSchema::Single(ty) => (
                self.type_reference(ty)?,
                Some(self.decode_expr("golemValue", ty, 0)?),
            ),
        };
        let awaited_ty = if ephemeral {
            format!("{RT}.InvocationResult<{ret_ty}>")
        } else {
            ret_ty.clone()
        };
        let receipt_ty = if ephemeral {
            format!("{RT}.InvocationReceipt")
        } else {
            "kotlin.Unit".to_string()
        };
        let decoder = format!("golemDecode{index}");
        let with_decls = |extra: &str| {
            [decls.as_str(), extra]
                .into_iter()
                .filter(|s| !s.is_empty())
                .collect::<Vec<_>>()
                .join(", ")
        };
        let input_line = format!("    val golemInput = {}", indent_tail(&input_expr));
        let doc = method.description.trim();
        let kdoc = |writer: &mut KotlinWriter, extra: &str| {
            let text = if doc.is_empty() {
                extra.to_string()
            } else {
                format!("{doc}\n\n{extra}")
            };
            writer.doc(&text);
        };

        let value_expr = match &decode {
            Some(dec) => format!(
                "val golemValue = golemResult.result ?: throw {RT}.BridgeException(\"Missing result value for an awaited invocation\")\n    {dec}"
            ),
            None => "kotlin.Unit".to_string(),
        };
        writer.line(format!(
            "private fun {decoder}(golemResult: {RT}.AgentInvocationResult): {awaited_ty} {{"
        ));
        writer.indent();
        if ephemeral {
            writer.line(format!("val golemOutcome = run {{\n    {value_expr}\n}}"));
            writer.line(format!(
                "return {RT}.InvocationResult(golemResult.agentId, golemResult.idempotencyKey, golemOutcome)"
            ));
        } else {
            writer.line(format!("return run {{\n    {value_expr}\n}}"));
        }
        writer.dedent();
        writer.line("}");
        writer.blank();

        if streaming {
            let lazy_input_line = format!(
                "    val golemInput: () -> {RT}.SchemaValue = {{ {} }}",
                indent_tail(&indent_block_body(&input_expr))
            );
            kdoc(
                writer,
                "Calls the method and blocks for its result. Stream parameters are sent and stream results are read through the streams themselves, which stay open after the call returns. Throws a bridge exception on failure.",
            );
            writer.line(format!("fun {}({decls}): {awaited_ty} {{", names.call));
            writer.line(lazy_input_line.clone());
            writer.line(format!(
                "    return {decoder}({RT}.Bridge.invokeStreamingAgent(golemResolved, {wire}, golemInput))"
            ));
            writer.line("}");
            writer.blank();

            kdoc(
                writer,
                "Starts the call and returns at once; the future completes with the result. A method that uses streams has no trigger or schedule form, because a fire-and-forget call has no connection to carry its streams.",
            );
            writer.line(format!(
                "fun {}({decls}): {FUTURE}<{awaited_ty}> {{",
                names.asynchronous
            ));
            writer.line(lazy_input_line);
            writer.line(format!(
                "    return {RT}.Bridge.invokeStreamingAgentAsync(golemResolved, {wire}, golemInput).thenApply {{ golemResult -> {decoder}(golemResult) }}"
            ));
            writer.line("}");
            return Ok(());
        }

        kdoc(
            writer,
            "Calls the method and blocks for its result. Throws a bridge exception on failure.",
        );
        writer.line(format!("fun {}({decls}): {awaited_ty} {{", names.call));
        writer.line(input_line.clone());
        writer.line(format!(
            "    return {decoder}({RT}.Bridge.invokeAgent(golemResolved, {wire}, golemInput, {}, null))",
            kotlin_string_literal(MODE_AWAIT)
        ));
        writer.line("}");
        writer.blank();

        kdoc(
            writer,
            "Starts the call and returns at once; the future completes with the result.",
        );
        writer.line(format!(
            "fun {}({decls}): {FUTURE}<{awaited_ty}> {{",
            names.asynchronous
        ));
        writer.line(input_line.clone());
        writer.line(format!(
            "    return {RT}.Bridge.invokeAgentAsync(golemResolved, {wire}, golemInput, {}, null).thenApply {{ golemResult -> {decoder}(golemResult) }}",
            kotlin_string_literal(MODE_AWAIT)
        ));
        writer.line("}");
        writer.blank();

        let receipt = if ephemeral {
            format!("{RT}.InvocationReceipt(golemResult.agentId, golemResult.idempotencyKey)")
        } else {
            "kotlin.Unit".to_string()
        };
        kdoc(writer, "Sends the call without waiting for the result.");
        writer.line(format!("fun {}({decls}): {receipt_ty} {{", names.trigger));
        writer.line(input_line.clone());
        writer.line(format!(
            "    val golemResult = {RT}.Bridge.invokeAgent(golemResolved, {wire}, golemInput, {}, null)",
            kotlin_string_literal(MODE_SCHEDULE)
        ));
        writer.line(format!("    return {receipt}"));
        writer.line("}");
        writer.blank();

        kdoc(writer, "Schedules the call for the given time.");
        writer.line(format!(
            "fun {}({}): {receipt_ty} {{",
            names.schedule,
            with_decls(&format!("golemAt: {RT}.Datetime"))
        ));
        writer.line(input_line);
        writer.line(format!(
            "    val golemResult = {RT}.Bridge.invokeAgent(golemResolved, {wire}, golemInput, {}, golemAt.toIsoString())",
            kotlin_string_literal(MODE_SCHEDULE)
        ));
        writer.line(format!("    return {receipt}"));
        writer.line("}");
        Ok(())
    }
}

/// Indents the lines between the first and last of a multi-line block expression by one level, so the body of a
/// `run { ... }` sits inside its braces.
fn indent_block_body(expr: &str) -> String {
    let lines: Vec<&str> = expr.split('\n').collect();
    let last = lines.len() - 1;
    lines
        .iter()
        .enumerate()
        .map(|(at, line)| {
            if at == 0 || at == last || line.is_empty() {
                (*line).to_string()
            } else {
                format!("    {line}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}
