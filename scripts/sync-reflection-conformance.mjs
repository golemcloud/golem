import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const corpusPath = path.join(root, 'test-data/reflection-conformance/v1.json');
const scalaPath = path.join(
  root,
  'sdks/scala/core/js/src/test/scala/golem/reflection/ReflectionConformanceCorpus.scala',
);
const moonBitPath = path.join(
  root,
  'sdks/moonbit/golem_sdk/reflection/reflection_conformance_corpus_wbtest.mbt',
);

const source = await readFile(corpusPath, 'utf8');
const corpus = JSON.parse(source);
const normalized = `${JSON.stringify(corpus, null, 2)}\n`;

if (corpus.version !== '1.0.0') throw new Error(`unexpected corpus version ${corpus.version}`);
if (corpus.schemaKinds.length !== 37) throw new Error('the corpus must enumerate all 37 schema kinds');
if (corpus.restrictionKinds.length !== 24)
  throw new Error('the corpus must enumerate all 24 restriction kinds');

const ids = corpus.cases.map((testCase) => testCase.id);
if (new Set(ids).size !== ids.length) throw new Error('conformance case IDs must be unique');
if (new Set(corpus.caseIds).size !== corpus.caseIds.length)
  throw new Error('declared conformance case IDs must be unique');
if (JSON.stringify([...ids].sort()) !== JSON.stringify([...corpus.caseIds].sort()))
  throw new Error('cases must exactly match the declared conformance case-ID set');
for (const testCase of corpus.cases) {
  for (const field of ['id', 'operation', 'fixture', 'expected']) {
    if (!(field in testCase)) throw new Error(`${testCase.id ?? '<unknown>'} is missing ${field}`);
  }
}

const scala = `/*
 * Copyright 2024-2026 Golem Cloud
 *
 * Licensed under the Golem Source License v1.1 (the "License");
 * you may not use this file except in compliance with the License.
 * You may obtain a copy of the License at
 *
 *     http://license.golem.cloud/LICENSE
 */

package golem.reflection

// Generated by scripts/sync-reflection-conformance.mjs. Do not edit.
private[reflection] object ReflectionConformanceCorpus {
  val json: String = """${normalized}"""
}
`;

const moonBit = `// Copyright 2024-2026 Golem Cloud
//
// Licensed under the Golem Source License v1.1 (the "License");
// you may not use this file except in compliance with the License.
// You may obtain a copy of the License at
//
//     http://license.golem.cloud/LICENSE

// Generated by scripts/sync-reflection-conformance.mjs. Do not edit.

///|
let reflection_conformance_corpus_json : String = ${JSON.stringify(normalized)}
`;

const generated = [
  [scalaPath, scala],
  [moonBitPath, moonBit],
];

if (process.argv.includes('--check')) {
  const stale = [];
  for (const [file, expected] of generated) {
    const actual = await readFile(file, 'utf8').catch(() => undefined);
    if (actual !== expected) stale.push(path.relative(root, file));
  }
  if (stale.length !== 0) {
    throw new Error(
      `reflection conformance embeds are stale: ${stale.join(', ')}; run node scripts/sync-reflection-conformance.mjs`,
    );
  }
} else {
  await Promise.all(generated.map(([file, contents]) => writeFile(file, contents)));
}
